#!/bin/sh
# garlic test suite.  POSIX sh, no test framework, no network: it needs only a
# built garlic, a C++ compiler for the unit tests, and the bundled example data.
#
#   sh test/run_tests.sh                 # from the repository root
#   GARLIC=/path/to/garlic sh test/run_tests.sh
#   sh test/run_tests.sh --bless         # rewrite the golden checksums
#
# Exits 0 if everything passes, 1 otherwise.

set -u

ROOT=$(cd "$(dirname "$0")/.." && pwd)
GARLIC=${GARLIC:-$ROOT/src/garlic}
# On MinGW the binary is garlic.exe.  The MSYS2 runtime usually resolves a stat
# of "garlic" to it, but relying on that makes the failure obscure when it does
# not; resolve it here instead.
[ -x "$GARLIC" ] || { [ -x "$GARLIC.exe" ] && GARLIC="$GARLIC.exe"; }
EX=$ROOT/example
GOLDEN=$ROOT/test/golden
WORK=${TMPDIR:-/tmp}/garlic-tests.$$
BLESS=no
[ "${1:-}" = "--bless" ] && BLESS=yes

pass=0; fail=0

# md5 is named differently on macOS and Linux.
if command -v md5sum >/dev/null 2>&1; then
    sum() { md5sum "$1" | cut -d' ' -f1; }
elif command -v md5 >/dev/null 2>&1; then
    sum() { md5 -q "$1"; }
else
    echo "ERROR: neither md5sum nor md5 found"; exit 1
fi

# gzip -cd is spelled the same on macOS and Linux; gzcat/zcat are not.
gz() { gzip -cd "$1"; }

# Builds a .tgls fixture from a tracked .tped: same four leading columns, the
# same number of genotype columns, every value set to $2.  Derived rather than
# committed so there is no new binary fixture to keep in step with the data.
# $1 = output, $2 = the value for every genotype, $3 = source TPED
# (default chr21.tped.gz).
mk_tgls() {
    gz "${3:-$EX/chr21.tped.gz}" | awk -v v="$2" '{
        printf "%s\t%s\t%s\t%s", $1, $2, $3, $4
        n = (NF - 4) / 2
        for (i = 0; i < n; i++) printf "\t%s", v
        printf "\n"
    }' | gzip > "$1"
}

# As mk_tgls, but puts $4 at locus $2 (1-based) for individual $3 and $5
# everywhere else -- for the guards that fire on a single bad value.
mk_tgls_one() {
    gz "$EX/chr21.tped.gz" | awk -v L="$2" -v S="$3" -v bad="$4" -v good="$5" '{
        printf "%s\t%s\t%s\t%s", $1, $2, $3, $4
        n = (NF - 4) / 2
        for (i = 0; i < n; i++) printf "\t%s", (NR == L && i == S) ? bad : good
        printf "\n"
    }' | gzip > "$1"
}
# Compare gzipped output by content, not by bytes: gzip embeds an mtime.
sumgz() { gzip -cd "$1" | { if command -v md5sum >/dev/null 2>&1; then md5sum; else md5 -q; fi; } | cut -d' ' -f1; }

ok()   { pass=$((pass+1)); }
bad()  { fail=$((fail+1)); echo "  FAIL  $1"; }

# ---------------------------------------------------------------------------
# 1. Unit tests
# ---------------------------------------------------------------------------
unit_tests() {
    echo "== unit tests =="
    CXX=${CXX:-c++}
    OBJ=""
    for o in "$ROOT"/src/*.o; do
        case "$o" in *garlic-main.o|*countFeatures*) continue;; esac
        [ -f "$o" ] && OBJ="$OBJ $o"
    done
    if [ -z "$OBJ" ]; then
        echo "  SKIP  no object files found (run make in src/ first)"
        return
    fi
    # zlib is the only external library left; garlic-math.o replaced GSL.
    #
    # zlib comes from the toolchain on every platform, MinGW included: the
    # vendored lib/win32/libz.a is a 32-bit i386 archive and a 64-bit MinGW
    # cannot link it at all, so pointing at it here (as an earlier version of
    # this stage did) only moved the failure.
    # shellcheck disable=SC2086
    if $CXX -O1 -std=c++11 -I"$ROOT/src" \
            "$ROOT/test/unit_tests.cpp" $OBJ -lz \
            -o "$WORK/unit_tests" 2>"$WORK/unit_build.log"; then
        if "$WORK/unit_tests"; then ok; else bad "unit tests reported failures"; fi
    else
        bad "unit tests did not compile (see $WORK/unit_build.log)"
    fi
}

# ---------------------------------------------------------------------------
# 2. Golden-output regression
#
# Every case below is fully specified -- explicit --lod-cutoff and
# --size-bounds where they exist, so no value is estimated and the output is a
# deterministic function of the input.  The auto-cutoff cases are included on
# purpose: --kde-subsample now defaults to 0, which removed the last consumer
# of random numbers on that path, so those are deterministic too and a
# regression there would reintroduce seed dependence.
# ---------------------------------------------------------------------------
# Every input named here is TRACKED in git, so a fresh clone can run this.
# The four chr21.* files were force-added for exactly that reason (.gitignore
# has *.gz).  The GQ fixtures are generated by mk_tgls rather than committed:
# example.GQ.tgls.gz is untracked, and naming it made tgls_gq skip permanently
# on any fresh clone.
#
# Most cases run on chr21 (8,599 loci) rather than genome-wide (577,489), so
# the suite is fast.  Four deliberately stay genome-wide because nothing
# smaller covers them: unweighted (22 chromosomes, per-chromosome centromere
# handling, genome-wide allele frequencies), chr_subset (needs more than one
# chromosome to select from), multiclass (needs a spread of ROH lengths to
# reach twelve size classes), and tgls_gl.
#
# TWO VACUITY TRAPS, both of which produced silently meaningless cases here
# before being caught:
#   - chr21.tgls.gz is a GL-convention file (-0.0004 everywhere, plus 9 exact
#     zeros).  Read as GQ, BOTH of those values convert to an error rate of 1,
#     so every LOD score is exactly 0: the raw matrix held 371,700 zeros and
#     2,655 NA, two distinct values, and the run called zero ROH.  The earlier
#     c21_tgls_rawlod case pinned that matrix -- non-empty, and still a
#     checksum of nothing.  It is replaced by c21_tgls_gq30, on a generated
#     GQ-30 fixture, whose raw matrix holds 274,055 distinct values; the
#     likelihood_guards stage asserts it equals the --error 0.001 run exactly,
#     which is the equivalence that makes the case meaningful rather than
#     merely non-empty.  chr21.tgls.gz is now rejected under every --gl-type:
#     negative values are invalid as GQ and PL, and its zeros are invalid as GL.
#   - example.GQ.tgls.gz is GQ 30 for every genotype, and GQ 30 converts to an
#     error rate of exactly 0.001, so tgls_gq reproduces the unweighted run
#     byte for byte.  That is expected, not a redundant case.
# The golden stage asserts every .roh.bed case called at least one ROH, so a
# case cannot silently become vacuous again.
#
# Every case is fully specified where it can be -- explicit --lod-cutoff and
# --size-bounds -- so no value is estimated and the output is a deterministic
# function of the input.  The auto-cutoff cases are included on purpose:
# --kde-subsample defaults to 0, which removed the last consumer of random
# numbers on that path, so a regression there would reintroduce seed
# dependence.
CASES="
unweighted|--tped $EX/example.tped.gz --tfam $EX/example.tfam --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000|roh.bed freq.gz
chr_subset|--tped $EX/example.tped.gz --tfam $EX/example.tfam --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --chr chr21 chr22|roh.bed
multiclass|--tped $EX/example.tped.gz --tfam $EX/example.tfam --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 1e5 2e5 3e5 5e5 1e6 2e6 3e6 4e6 5e6 6e6 7e6|roh.bed
tgls_gl|--tped $EX/example.tped.gz --tfam $EX/example.tfam --tgls $EX/example.tgls.gz --gl-type GL --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000|roh.bed
c21_unweighted|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000|roh.bed freq.gz
c21_autocutoff|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --winsize 60 --error 0.001|roh.bed
c21_autowinsize|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --auto-winsize --winsize 30 --error 0.001|roh.bed
c21_weighted|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --map $EX/chr21.map.gz --weighted --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000|roh.bed
c21_cm|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --map $EX/chr21.map.gz --cm --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 0.5 1.0|roh.bed
c21_phased|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --phased --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000|roh.bed
c21_froh|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --froh|roh.bed froh.tsv
c21_rawlod|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --raw-lod|chr21.raw.lod.windows.gz
c21_freqonly|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --error 0.001 --freq-only|freq.gz
c21_tgls_gq30|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --tgls $WORK/gq30.tgls.gz --gl-type GQ --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --raw-lod|chr21.raw.lod.windows.gz
tgls_gq|--tped $EX/example.tped.gz --tfam $EX/example.tfam --tgls $WORK/gq30_genome.tgls.gz --gl-type GQ --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000|roh.bed
"

golden() {
    echo "== golden output =="
    echo "$CASES" | while IFS='|' read -r name args outs; do
        [ -z "$name" ] && continue
        out=$WORK/$name
        # Skip rather than fail when an input is not in the repository.
        missing=
        for tok in $args; do
            case "$tok" in
                */*.gz|*/*.tfam|*/*.tped) [ -f "$tok" ] || missing="$missing $tok";;
            esac
        done
        if [ -n "$missing" ]; then
            echo "  SKIP  $name: input not present:$missing"
            continue
        fi
        # shellcheck disable=SC2086
        $GARLIC $args --out "$out" --quiet --force >"$WORK/$name.stdout" 2>"$WORK/$name.stderr"
        rc=$?
        if [ "$rc" -ne 0 ]; then
            echo "  FAIL  $name: garlic exited $rc (see $WORK/$name.stderr)"
            echo x >>"$WORK/failures"; continue
        fi
        for suffix in $outs; do
            f=$out.$suffix
            if [ ! -f "$f" ]; then
                echo "  FAIL  $name: expected output $name.$suffix was not created"
                echo x >>"$WORK/failures"; continue
            fi
            # A case that calls no ROH compares two empty files and proves
            # nothing.  This is how two vacuous cases got into this suite.
            case "$suffix" in
                roh.bed)
                    # NOT 'grep -vc ... || echo 0': grep -vc prints 0 AND
                    # exits 1 when nothing matches, so the || fires too and
                    # tracts becomes "0\n0", which makes [ -eq ] a syntax
                    # error and this guard silently never fires.  wc always
                    # exits 0.
                    tracts=$(grep -v '^track' "$f" 2>/dev/null | wc -l | tr -d ' ')
                    if [ "$tracts" -eq 0 ]; then
                        echo "  FAIL  $name: called 0 ROH -- this case is vacuous"
                        echo x >>"$WORK/failures"; continue
                    fi
                    ;;
            esac
            case "$suffix" in *.gz) got=$(sumgz "$f");; *) got=$(sum "$f");; esac
            g=$GOLDEN/$name.$suffix.md5
            if [ "$BLESS" = yes ]; then
                echo "$got" >"$g"
                continue
            fi
            if [ ! -f "$g" ]; then
                echo "  FAIL  $name.$suffix: no golden checksum (run with --bless)"
                echo x >>"$WORK/failures"; continue
            fi
            _gold_want=$(cat "$g")
            if [ "$got" != "$_gold_want" ]; then
                echo "  FAIL  $name.$suffix: $got != $_gold_want"
                echo "        output kept at $f"
                echo x >>"$WORK/failures"
            fi
        done
    done
    if [ "$BLESS" = yes ]; then echo "  blessed $(ls "$GOLDEN" | wc -l | tr -d ' ') checksums"; ok; return; fi
    if [ -s "$WORK/failures" ]; then fail=$((fail + $(wc -l <"$WORK/failures"))); : >"$WORK/failures"; else ok; fi
}

# ---------------------------------------------------------------------------
# 3. Determinism: the auto-cutoff path must not depend on the drawn seed
# ---------------------------------------------------------------------------
determinism() {
    echo "== determinism =="
    for i in 1 2 3; do
        $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 \
                --winsize 60 --error 0.001 --out "$WORK/det$i" --quiet --force >/dev/null 2>&1
    done
    a=$(sum "$WORK/det1.roh.bed"); b=$(sum "$WORK/det2.roh.bed"); c=$(sum "$WORK/det3.roh.bed")
    if [ "$a" = "$b" ] && [ "$b" = "$c" ]; then
        s1=$(wc -l <"$WORK/det1.params.json" 2>/dev/null | tr -d ' ')
        [ -n "$s1" ] || s1=0
        [ "$s1" -gt 0 ] || bad "no params.json written"
        ok
    else
        bad "three auto-cutoff runs disagree ($a $b $c) -- the KDE path is seed dependent again"
    fi
}

# ---------------------------------------------------------------------------
# 4. Exit-code contract: 0 success, 1 usage error, 2 runtime error
# ---------------------------------------------------------------------------
# NOTE: sh has no local variables, so every name assigned here is assigned in
# the CALLING stage's scope.  A stage that used "want" for its own expected
# value and then called expect_exit got that value silently replaced by the
# expected exit status, and the comparison afterwards still looked like a real
# assertion.  Hence the underscore prefixes: they are this function's, and no
# stage should use them.
expect_exit() {
    _ee_want=$1; _ee_what=$2; shift 2
    # Keep stderr.  It used to be discarded, which made every exit-code failure
    # in this suite undiagnosable from a CI log -- you could see that garlic
    # returned the wrong status but not what it thought it was doing.  On
    # failure the program's own diagnosis is worth more than the status is.
    "$@" >/dev/null 2>"$WORK/.expect_exit.err"
    _ee_got=$?
    if [ "$_ee_got" -eq "$_ee_want" ]; then ok
    else
        bad "$_ee_what: exit $_ee_got, expected $_ee_want"
        sed -n '1,3p' "$WORK/.expect_exit.err" | sed 's/^/        /'
    fi
}

exit_codes() {
    echo "== exit codes =="
    expect_exit 0 "--version" "$GARLIC" --version
    expect_exit 0 "--help" "$GARLIC" --help
    expect_exit 0 "-h" "$GARLIC" -h
    expect_exit 1 "no arguments" "$GARLIC"
    expect_exit 1 "unrecognised flag" "$GARLIC" --not-a-real-flag
    expect_exit 1 "missing tped" "$GARLIC" --tped /nonexistent.tped.gz --tfam "$EX/example.tfam" --build hg18 --winsize 60 --out "$WORK/e1"
    expect_exit 1 "no build and no centromere file" "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --winsize 60 --out "$WORK/e2"
    expect_exit 1 "winsize below the minimum" "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 --winsize 1 --out "$WORK/e3"
    expect_exit 1 "--chr naming a chromosome not in the data" "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 --winsize 60 --lod-cutoff 2.5 --chr chr99 --out "$WORK/e4"
    expect_exit 1 "--load-params on a missing file" "$GARLIC" --load-params /nonexistent.json --out "$WORK/e5"
    expect_exit 1 "--weighted without a map" "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --weighted --build hg18 --winsize 60 --out "$WORK/e6"
    expect_exit 2 "cutoff selection fails (--mode-smooth-span too wide)" "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 --winsize 60 --error 0.001 --mode-smooth-span 400 --out "$WORK/e7"

    # A rejected command line must not leave output files behind.
    rm -f "$WORK/noclobber".*
    $GARLIC --tped "$EX/example.tped.gz" --not-a-real-flag --out "$WORK/noclobber" >/dev/null 2>&1
    if ls "$WORK/noclobber".* >/dev/null 2>&1; then
        bad "a rejected command line created output files: $(ls "$WORK/noclobber".*)"
    else ok; fi

    # --force is required to overwrite existing calls.
    $GARLIC --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/clob" --quiet >/dev/null 2>&1
    expect_exit 1 "second run without --force refuses to clobber" "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/clob" --quiet

    # A successful run must not create an empty .error file.
    if [ -f "$WORK/clob.error" ]; then bad "a successful run created a .error file"; else ok; fi
}

# ---------------------------------------------------------------------------
# 4b. Genotype-likelihood guards
# ---------------------------------------------------------------------------
# A tgls file states P(genotype CORRECT) for PL and GL, which is NOT what a
# VCF's PL/GL fields carry: VCF normalises them so the CALLED genotype is
# exactly 0.  Feeding those in used to run to completion with an error rate of
# 0 clamped to 1e-16, which makes every heterozygote contribute -16 to the
# window LOD -- 113 ROH instead of 171 on this data, with no other symptom.
# These are the checks that reject such input instead of computing with it.
#
# The fixtures are generated from chr21.tped.gz so the row and column counts
# match; the guards fire on the first offending value, but the file still has
# to be the right shape to reach them.
likelihood_guards() {
    echo "== genotype likelihood guards =="

    # An exact 0 is P(genotype correct) = 1, which no measurement supports and
    # which is exactly what VCF normalisation writes.  Field-specific: a GQ of
    # 0 legitimately means "no confidence".
    mk_tgls_one "$WORK/zero_gl.tgls.gz" 500 7 0 -0.0004
    mk_tgls_one "$WORK/zero_pl.tgls.gz" 500 7 0 0.00435
    expect_exit 2 "GL of exactly 0 is rejected" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/zero_gl.tgls.gz" --gl-type GL \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g1" --force
    expect_exit 2 "PL of exactly 0 is rejected" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/zero_pl.tgls.gz" --gl-type PL \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g2" --force

    # No INTEGER PL expresses a realistic error rate under this convention:
    # they map to 0, 0.206, 0.369, 0.499, ... while 0.001 needs PL = 0.00435.
    # So an all-integer PL file came from a VCF however it was produced.
    mk_tgls "$WORK/int_pl.tgls.gz" 3
    expect_exit 2 "all-integer PL file is rejected" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/int_pl.tgls.gz" --gl-type PL \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g3" --force
    # ... and the same file as GQ is fine: integer GQ is the native scale.
    expect_exit 0 "the same file as GQ is accepted" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/int_pl.tgls.gz" --gl-type GQ \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g4" --force

    # Values impossible on their own scale.
    mk_tgls_one "$WORK/neg_gq.tgls.gz" 3 0 -1 30
    mk_tgls_one "$WORK/pos_gl.tgls.gz" 3 0 0.5 -0.0004
    mk_tgls_one "$WORK/junk.tgls.gz"   9 3 NA 30
    expect_exit 2 "negative GQ is rejected" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/neg_gq.tgls.gz" --gl-type GQ \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g5" --force
    expect_exit 2 "positive GL is rejected" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/pos_gl.tgls.gz" --gl-type GL \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g6" --force
    # An unparseable token used to leave the value at 0 and fail the stream, so
    # the rest of the line silently became zeros.
    expect_exit 2 "an unparseable value is rejected" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/junk.tgls.gz" --gl-type GQ \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g7" --force

    # A fractional PL file is what the convention actually asks for, and runs.
    mk_tgls "$WORK/frac_pl.tgls.gz" 0.00435
    expect_exit 0 "a fractional PL file is accepted" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/frac_pl.tgls.gz" --gl-type PL \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g8" --force

    # The shipped chr21.tgls.gz is now invalid under every --gl-type: it holds
    # negative values (invalid as GQ and PL) and exact zeros (invalid as GL).
    # This is the file the replaced c21_tgls_rawlod case used to read as GQ.
    if [ -f "$EX/chr21.tgls.gz" ]; then
        expect_exit 2 "shipped chr21.tgls.gz rejected as GQ" "$GARLIC" --tped "$EX/chr21.tped.gz" \
            --tfam "$EX/chr21.tfam.gz" --tgls "$EX/chr21.tgls.gz" --gl-type GQ \
            --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g9" --force
        expect_exit 2 "shipped chr21.tgls.gz rejected as GL" "$GARLIC" --tped "$EX/chr21.tped.gz" \
            --tfam "$EX/chr21.tfam.gz" --tgls "$EX/chr21.tgls.gz" --gl-type GL \
            --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/g10" --force
    else
        echo "  SKIP shipped chr21.tgls.gz: input not present"
    fi

    # The equivalence that makes c21_tgls_gq30 a real case rather than a
    # non-empty one: GQ 30 IS an error rate of 0.001, so supplying it per
    # genotype must reproduce --error 0.001 exactly.  If the GQ conversion ever
    # drifts, these two stop matching.
    $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --tgls "$WORK/gq30.tgls.gz" \
        --gl-type GQ --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --raw-lod --out "$WORK/eqgq" --quiet --force >/dev/null 2>&1
    $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --error 0.001 \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --raw-lod --out "$WORK/eqfl" --quiet --force >/dev/null 2>&1
    if [ "$(sum "$WORK/eqgq.chr21.raw.lod.windows.gz")" = "$(sum "$WORK/eqfl.chr21.raw.lod.windows.gz")" ]; then
        ok
    else
        bad "GQ 30 per genotype did not reproduce --error 0.001"
    fi
    # ... and that case must not be vacuous the way the one it replaced was.
    n=$(gz "$WORK/eqgq.chr21.raw.lod.windows.gz" | tr -s ' \t' '\n' | sort -u | grep -c .)
    if [ "$n" -gt 1000 ]; then ok; else bad "c21_tgls_gq30 raw LOD has only $n distinct values"; fi

    # The genome-wide GQ-30 case must equal the genome-wide --error 0.001 run,
    # for the same reason.  Compares the OUTPUTS, not the two golden checksum
    # files: those are static text and would still match after a code change,
    # so comparing them would only catch a bad re-bless.  This fires on any
    # drift in the GQ conversion even if both goldens were re-blessed together.
    # shellcheck disable=SC2086
    $GARLIC --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" \
            --tgls "$WORK/gq30_genome.tgls.gz" --gl-type GQ --build hg18 --winsize 60 \
            --lod-cutoff 2.5 --size-bounds 500000 1000000 \
            --out "$WORK/gwgq" --quiet --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    $GARLIC --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" \
            --error 0.001 --build hg18 --winsize 60 \
            --lod-cutoff 2.5 --size-bounds 500000 1000000 \
            --out "$WORK/gwerr" --quiet --force >/dev/null 2>&1
    if cmp -s "$WORK/gwgq.roh.bed" "$WORK/gwerr.roh.bed"; then ok
    else bad "genome-wide GQ 30 did not equal --error 0.001"; fi
}

# ---------------------------------------------------------------------------
# 4c. Individual metadata
# ---------------------------------------------------------------------------
# The duplicate-ID error and the pooled-population warning were moved out of
# scanIndData3, which only --tfam calls, into checkIndData over the assembled
# IndData, so they apply to every input path.  These cases pin the TFAM path's
# behaviour across that move: same messages, same exit codes.  The pooled-
# population warning in particular is what catches a TFAM with population 0
# for every sample, which is what the deprecated vcf2tped.pl writes.
ind_metadata() {
    echo "== individual metadata =="

    # A duplicate individual ID.
    gz "$EX/chr21.tfam.gz" | awk 'NR==5{$2="HGDP00607"} {print $1"\t"$2"\t"$3"\t"$4"\t"$5"\t"$6}' > "$WORK/dup.tfam"
    expect_exit 2 "a duplicate individual ID is rejected" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$WORK/dup.tfam" --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 \
        --size-bounds 500000 1000000 --out "$WORK/i1" --force
    if "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$WORK/dup.tfam" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/i1" --force \
            2>&1 | grep -q "Found duplicate individual ID"; then ok
    else bad "the duplicate-ID error message is missing"; fi

    # Two populations in one file: allowed, but it must say so, because
    # frequencies are pooled across all of them.
    gz "$EX/chr21.tfam.gz" | awk 'NR>20{$1="OTHERPOP"} {print $1"\t"$2"\t"$3"\t"$4"\t"$5"\t"$6}' > "$WORK/twopop.tfam"
    expect_exit 0 "two populations in one TFAM still runs" "$GARLIC" --tped "$EX/chr21.tped.gz" \
        --tfam "$WORK/twopop.tfam" --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 \
        --size-bounds 500000 1000000 --out "$WORK/i2" --force
    # This used to warn that frequencies were pooled and tell the user to run
    # each population separately.  garlic now does exactly that by itself, so
    # the run REPORTS the split instead of warning about it.
    if "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$WORK/twopop.tfam" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/i2" --force \
            2>&1 | grep -q "Populations found: 2"; then ok
    else bad "a two-population TFAM did not report the populations it found"; fi
    if [ -f "$WORK/i2.OTHERPOP.roh.bed" ] && [ ! -f "$WORK/i2.roh.bed" ]; then ok
    else bad "a two-population TFAM did not produce per-population output files"; fi

    # A single-population TFAM must NOT warn.
    if "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/i3" --force \
            2>&1 | grep -q "Found multiple population IDs"; then
        bad "a single-population TFAM produced the pooled-population warning"
    else ok; fi
    # An undeclared sex chromosome stops the run, and the message reports what
    # the sex metadata actually says.  It must never state a number of
    # AFFECTED individuals the metadata cannot support: sex is optional in a
    # TFAM, so all three coverage cases are reachable, and the partial case
    # used to print only the male count -- 3 of 45 coded male with 42 unknown
    # printed "individuals coded male in the TFAM: 3", and 3 reads as the
    # answer when up to 45 could be affected.  The counts below are raw
    # metadata, which is the only thing that can be stated without a claim.
    gz "$EX/chr21.tped.gz" | sed 's/^21/chrX/' | gzip > "$WORK/chrX.tped.gz"
    gz "$EX/chr21.tfam.gz" | awk '{print $1"\t"$2}' > "$WORK/nosex.tfam"
    gz "$EX/chr21.tfam.gz" | awk 'NR<=3{print $1"\t"$2"\t0\t0\t1\t0"} NR>3{print $1"\t"$2}' > "$WORK/partial.tfam"
    sexwarn() {   # $1 = tfam, $2 = pattern that must appear
        out=$("$GARLIC" --tped "$WORK/chrX.tped.gz" --tfam "$1" --build hg18 --winsize 60 \
                --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
                --out "$WORK/sx" --force 2>&1)
        st=$?
        if [ "$st" -ne 1 ]; then
            bad "undeclared chrX on $(basename "$1") exited $st, expected 1"
        elif printf '%s\n' "$out" | grep -q "$2"; then ok
        else bad "sex report on $(basename "$1"): expected /$2/"; fi
    }
    sexwarn "$WORK/nosex.tfam"  "Sex is not recorded for any of the 45"
    sexwarn "$WORK/partial.tfam" "3 male, 0 female, 42 unknown"
    sexwarn "$EX/chr21.tfam.gz" "26 male, 19 female"
    sexwarn "$EX/chr21.tfam.gz" "has not been told how to treat: chrX"
    # ... and no run may state a bare affected count, which is the misleading
    # form this used to print.  Nothing can be said about how many individuals
    # are affected while any of them has no recorded sex.
    if "$GARLIC" --tped "$WORK/chrX.tped.gz" --tfam "$WORK/partial.tfam" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --out "$WORK/sx" --force 2>&1 \
            | grep -q "affected individuals:"; then
        bad "a partial-coverage run stated a bare affected count"
    else ok; fi
    # --- --pop -------------------------------------------------------------
    # Rows are matched by sample ID, never by position.  The column order is
    # <id> <pop>, which is the OPPOSITE of a TFAM's, so a TFAM-ordered file is
    # the mistake the format invites and gets its own diagnostic.
    gz "$EX/chr21.tfam.gz" | awk '{print $2"\tFrench"}'          > "$WORK/good.pop"
    gz "$EX/chr21.tfam.gz" | awk '{print $2"\tFrench\t"$5}'      > "$WORK/withsex.pop"
    gz "$EX/chr21.tfam.gz" | awk '{print $1"\t"$2}'              > "$WORK/swapped.pop"
    gz "$EX/chr21.tfam.gz" | awk 'NR>1{print $2"\tFrench"}'      > "$WORK/missing1.pop"
    gz "$EX/chr21.tfam.gz" | awk 'NR==3{print $2"\tFrench"} {print $2"\tFrench"}' > "$WORK/dup.pop"
    gz "$EX/chr21.tfam.gz" | awk '{print $2"\tFrench\t7"}'       > "$WORK/badsex.pop"
    gz "$EX/chr21.tfam.gz" | awk '{print $2"\tFre\"nch"}'        > "$WORK/quote.pop"
    gz "$EX/chr21.tfam.gz" | awk 'NR<=20{print $2"\tPopA"} NR>20{print $2"\tPopB"}' > "$WORK/twopop.pop"
    { cat "$WORK/good.pop"; printf 'NOT_A_SAMPLE\tElsewhere\nALSO_NOT\tElsewhere\n'; } > "$WORK/extra.pop"

    POPBASE="--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000"
    poprun() {  # $1 = pop file, $2 = expected exit, $3 = label
        # shellcheck disable=SC2086
        expect_exit "$2" "$3" "$GARLIC" $POPBASE --pop "$1" --out "$WORK/p1" --force
    }
    poprun "$WORK/swapped.pop"  2 "--pop with TFAM-ordered columns is rejected"
    poprun "$WORK/missing1.pop" 2 "--pop missing a sample is rejected"
    poprun "$WORK/dup.pop"      2 "--pop with a duplicate ID is rejected"
    poprun "$WORK/badsex.pop"   2 "--pop with an unrecognised sex value is rejected"
    poprun "$WORK/quote.pop"    2 "--pop with a quote in a label is rejected"
    poprun "$WORK/good.pop"     0 "--pop with well-formed input is accepted"
    poprun "$WORK/extra.pop"    0 "--pop with extra rows is accepted"

    # The swapped file must get the SWAP diagnostic, not the duplicate-ID one.
    # Column 1 of a TFAM is the population, identical on every row, so a
    # duplicate check running first would hide the message that explains the
    # mistake.  These two are easy to conflate, which is why this is asserted.
    # shellcheck disable=SC2086
    if "$GARLIC" $POPBASE --pop "$WORK/swapped.pop" --out "$WORK/p2" --force 2>&1 \
            | grep -q "looks like its columns are swapped"; then ok
    else bad "--pop swapped columns did not produce the swap diagnostic"; fi

    # The override must reach the outputs: the FROH pop column and the BED
    # track name both carry pop[ind], and the calls must not change.
    # shellcheck disable=SC2086
    $GARLIC $POPBASE --pop "$WORK/good.pop" --froh --out "$WORK/pg" --quiet --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    $GARLIC $POPBASE --froh --out "$WORK/pn" --quiet --force >/dev/null 2>&1
    if [ "$(grep -v '^##' "$WORK/pg.froh.tsv" | awk 'NR==2{print $2}')" = "French" ] &&
       [ "$(grep -v '^##' "$WORK/pn.froh.tsv" | awk 'NR==2{print $2}')" != "French" ]; then ok
    else bad "--pop did not reach the FROH population column"; fi
    grep -v '^track' "$WORK/pg.roh.bed" > "$WORK/pg.notrack"
    grep -v '^track' "$WORK/pn.roh.bed" > "$WORK/pn.notrack"
    if cmp -s "$WORK/pg.notrack" "$WORK/pn.notrack"; then ok
    else bad "--pop changed the calls, not just the labels"; fi

    # enumeratePopulations must see the OVERRIDDEN labels, which is why
    # applyPopFile runs before it: a single-population TFAM relabelled into two
    # populations by --pop must be ANALYSED as two.
    # shellcheck disable=SC2086
    if "$GARLIC" $POPBASE --pop "$WORK/twopop.pop" --out "$WORK/p3" --force 2>&1 \
            | grep -q "Populations found: 2"; then ok
    else bad "--pop introducing two populations was not split"; fi

    # --pop's sex column must feed the sex-chromosome warning, which is the
    # reason the column exists.
    gz "$EX/chr21.tfam.gz" | awk '{print $1"\t"$2}' > "$WORK/nosex2.tfam"
    if "$GARLIC" --tped "$WORK/chrX.tped.gz" --tfam "$WORK/nosex2.tfam" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --pop "$WORK/withsex.pop" \
            --out "$WORK/p4" --force 2>&1 | grep -q "26 male, 19 female"; then ok
    else bad "--pop sex column did not reach the sex-chromosome warning"; fi
}

# ---------------------------------------------------------------------------
# 4d. VCF input
# ---------------------------------------------------------------------------
# The headline property: the SAME genotypes in two formats must produce the
# same calls.  The fixture is generated from chr21.tped.gz with REF/ALT chosen
# ALPHABETICALLY, which is deliberately NOT how garlic picks its counted allele
# (the first non-missing allele in individual order), so the dosage is flipped
# at roughly half the loci -- 4,390 of 8,599 as generated here.  A bit-identical
# raw LOD matrix across that flip is what makes "count ALT instead" safe.
vcf_input() {
    echo "== VCF input =="

    # ---- build the fixture ----
    gz "$EX/chr21.tfam.gz" | awk '{printf "\t%s", $2} END{print ""}' > "$WORK/vcf.samples"
    {
        printf '##fileformat=VCFv4.2\n'
        printf '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
        printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT'
        cat "$WORK/vcf.samples"
        gz "$EX/chr21.tped.gz" | awk '
        {
            delete seen; n = 0
            for (i = 5; i <= NF; i++) if ($i != "0" && !($i in seen)) { seen[$i] = 1; a[++n] = $i }
            if (n == 0) next
            if (n == 1) { ref = a[1]; alt = (ref == "A" ? "C" : (ref == "C" ? "A" : (ref == "G" ? "T" : "G"))) }
            else if (a[1] < a[2]) { ref = a[1]; alt = a[2] }
            else                  { ref = a[2]; alt = a[1] }
            line = $1 "\t" $4 "\t" $2 "\t" ref "\t" alt "\t.\tPASS\t.\tGT"
            for (i = 5; i <= NF; i += 2) {
                if ($i == "0" || $(i+1) == "0") g = "./."
                else g = ($i == alt ? 1 : 0) "/" ($(i+1) == alt ? 1 : 0)
                line = line "\t" g
            }
            print line
        }'
    } > "$WORK/chr21.vcf"
    gzip -c "$WORK/chr21.vcf" > "$WORK/chr21.vcf.gz"
    gz "$EX/chr21.tfam.gz" | awk '{print $2"\t"$1}' > "$WORK/vcf.pop"

    VB="--build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000"

    # ---- the equivalence ----
    # shellcheck disable=SC2086
    $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" $VB --raw-lod \
            --out "$WORK/vt" --quiet --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    $GARLIC --vcf "$WORK/chr21.vcf.gz" --pop "$WORK/vcf.pop" $VB --raw-lod \
            --out "$WORK/vv" --quiet --force >/dev/null 2>&1
    if [ -f "$WORK/vv.roh.bed" ]; then ok; else bad "--vcf produced no output"; fi
    grep -v '^track' "$WORK/vt.roh.bed" > "$WORK/vt.nt" 2>/dev/null
    grep -v '^track' "$WORK/vv.roh.bed" > "$WORK/vv.nt" 2>/dev/null
    if cmp -s "$WORK/vt.nt" "$WORK/vv.nt"; then ok
    else bad "--vcf and --tped called different ROH from the same genotypes"; fi
    gz "$WORK/vt.chr21.raw.lod.windows.gz" > "$WORK/vt.raw"
    gz "$WORK/vv.chr21.raw.lod.windows.gz" > "$WORK/vv.raw"
    if cmp -s "$WORK/vt.raw" "$WORK/vv.raw"; then ok
    else bad "--vcf and --tped produced different raw LOD scores"; fi
    # the run must not be vacuous
    n=$(grep -vc '^track' "$WORK/vv.roh.bed" 2>/dev/null || echo 0)
    if [ "$n" -gt 0 ]; then ok; else bad "the --vcf equivalence case called no ROH"; fi

    # ---- --freq-only streams, and must agree with the in-memory pass ----
    # shellcheck disable=SC2086
    $GARLIC --vcf "$WORK/chr21.vcf.gz" --pop "$WORK/vcf.pop" --build hg18 --error 0.001 \
            --freq-only --out "$WORK/vfo" --quiet --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    $GARLIC --vcf "$WORK/chr21.vcf.gz" --pop "$WORK/vcf.pop" $VB \
            --out "$WORK/vmem" --quiet --force >/dev/null 2>&1
    gz "$WORK/vfo.freq.gz"  > "$WORK/vfo.freq"
    gz "$WORK/vmem.freq.gz" > "$WORK/vmem.freq"
    if cmp -s "$WORK/vfo.freq" "$WORK/vmem.freq"; then ok
    else bad "freqOnlyVCF disagrees with loadVCFData's frequencies"; fi

    # ---- a frequency file must cross between the two readers ----
    # readFreqData compares the ALLELE column against mapData->allele and flips
    # to 1-f on a mismatch, which is what makes this work at the 4,390 loci
    # where the two readers count different alleles.
    # shellcheck disable=SC2086
    $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 --error 0.001 \
            --freq-only --out "$WORK/tfo" --quiet --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" $VB \
            --freq-file "$WORK/vfo.freq.gz" --out "$WORK/xtv" --quiet --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    $GARLIC --vcf "$WORK/chr21.vcf.gz" --pop "$WORK/vcf.pop" $VB \
            --freq-file "$WORK/tfo.freq.gz" --out "$WORK/xvt" --quiet --force >/dev/null 2>&1
    grep -v '^track' "$WORK/xtv.roh.bed" > "$WORK/xtv.nt" 2>/dev/null
    grep -v '^track' "$WORK/xvt.roh.bed" > "$WORK/xvt.nt" 2>/dev/null
    if cmp -s "$WORK/vt.nt" "$WORK/xtv.nt" && cmp -s "$WORK/vt.nt" "$WORK/xvt.nt"; then ok
    else bad "a frequency file did not cross between the --tped and --vcf readers"; fi

    # ---- mutual exclusion ----
    # The MESSAGE is asserted, not just the exit code: an unrecognised flag also
    # exits 1, so an exit-only check here would pass against a binary that has
    # no --vcf at all.
    mutex() {  # $1 = pattern, $2 = label, rest = args
        pat=$1; lbl=$2; shift 2
        # shellcheck disable=SC2086
        if "$GARLIC" "$@" 2>&1 | grep -q "$pat"; then ok; else bad "$lbl"; fi
    }
    mutex "alternative sources of the same data" "--vcf with --tped not diagnosed" \
        --vcf "$WORK/chr21.vcf.gz" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" \
        --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --out "$WORK/v1" --force
    mutex "so --tfam is not used" "--vcf with --tfam not diagnosed" \
        --vcf "$WORK/chr21.vcf.gz" --tfam "$EX/chr21.tfam.gz" \
        --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --out "$WORK/v2" --force
    expect_exit 1 "--vcf with --tped exits 1" "$GARLIC" --vcf "$WORK/chr21.vcf.gz" \
        --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 --winsize 60 \
        --error 0.001 --lod-cutoff 2.5 --out "$WORK/v1" --force

    # ---- malformed VCFs ----
    HDR=$(head -3 "$WORK/chr21.vcf")
    vcfmut() {  # $1 = out, $2 = awk program applied to the data lines
        { printf '%s\n' "$HDR"; tail -n +4 "$WORK/chr21.vcf" | head -400 | awk -F'\t' -v OFS='\t' "$2"; } > "$1"
    }
    vcfmut "$WORK/inter.vcf"    '{ $1 = (NR % 2 == 1 ? "21" : "22"); print }'
    vcfmut "$WORK/haploid.vcf"  '{ if (NR == 8) $13 = "1"; print }'
    vcfmut "$WORK/triploid.vcf" '{ if (NR == 8) $13 = "0/1/1"; print }'
    vcfmut "$WORK/phased.vcf"   '{ for (i = 10; i <= NF; i++) gsub("/", "|", $i); print }'
    vcfmut "$WORK/ph1un.vcf"    '{ for (i = 10; i <= NF; i++) gsub("/", "|", $i); if (NR == 8) gsub("\\|", "/", $13); print }'
    vcfmut "$WORK/indel.vcf"    '{ if (NR == 8) $4 = "AT"; print }'
    vcfmut "$WORK/multi.vcf"    '{ if (NR == 8) $5 = "G,T"; print }'
    vcfmut "$WORK/lowq.vcf"     '{ if (NR == 8) $7 = "LowQual"; print }'
    printf '##fileformat=VCFv4.2\n' > "$WORK/onlymeta.vcf"

    vcfrun() {  # $1 = file, $2 = expected exit, $3 = label; extra args after
        f=$1; e=$2; l=$3; shift 3
        # shellcheck disable=SC2086
        expect_exit "$e" "$l" "$GARLIC" --vcf "$f" --pop "$WORK/vcf.pop" $VB \
            --out "$WORK/vr" --force "$@"
    }
    vcfrun "$WORK/inter.vcf"    2 "an interleaved VCF is rejected"
    vcfrun "$WORK/haploid.vcf"  2 "a haploid call is rejected"
    vcfrun "$WORK/triploid.vcf" 2 "a triploid call is rejected"
    vcfrun "$WORK/onlymeta.vcf" 2 "a VCF with no #CHROM header is rejected"
    vcfrun "$WORK/phased.vcf"   0 "an all-phased VCF is accepted with --phased" --phased
    vcfrun "$WORK/ph1un.vcf"    2 "one unphased call is rejected under --phased" --phased

    # ---- skipped sites are skipped AND counted ----
    skipmsg() {  # $1 = file, $2 = pattern
        # shellcheck disable=SC2086
        $GARLIC --vcf "$1" --pop "$WORK/vcf.pop" $VB --out "$WORK/vs" --force >/dev/null 2>&1
        if grep -q "$2" "$WORK/vs.log"; then ok; else bad "VCF skip not reported: /$2/"; fi
    }
    skipmsg "$WORK/indel.vcf" "Sites skipped, not a SNV: 1"
    skipmsg "$WORK/multi.vcf" "Sites skipped, multiallelic: 1"
    skipmsg "$WORK/lowq.vcf"  "FILTER not PASS, KEPT"
    # shellcheck disable=SC2086
    $GARLIC --vcf "$WORK/lowq.vcf" --pop "$WORK/vcf.pop" $VB --vcf-pass-only \
            --out "$WORK/vp" --force >/dev/null 2>&1
    if grep -q "Sites skipped, FILTER not PASS: 1" "$WORK/vp.log"; then ok
    else bad "--vcf-pass-only did not report the skipped site"; fi

    # ---- omitting --pop is allowed but must say so ----
    # shellcheck disable=SC2086
    if $GARLIC --vcf "$WORK/chr21.vcf.gz" $VB --out "$WORK/vnp" --force 2>&1 \
            | grep -q "no --pop given"; then ok
    else bad "--vcf without --pop did not warn"; fi
    # ---- BGZF ----
    # A VCF from bcftools or GATK is BGZF, not plain gzip: multi-member gzip
    # with a BC extra field per block and an EOF marker.  igzstream reads it
    # because BGZF is valid gzip.  Skipped rather than failed where bgzip is
    # absent, since it is not a build dependency.
    if command -v bgzip >/dev/null 2>&1; then
        bgzip -c "$WORK/chr21.vcf" > "$WORK/chr21.bgzf.vcf.gz"
        # shellcheck disable=SC2086
        $GARLIC --vcf "$WORK/chr21.bgzf.vcf.gz" --pop "$WORK/vcf.pop" $VB \
                --out "$WORK/vbg" --quiet --force >/dev/null 2>&1
        grep -v '^track' "$WORK/vbg.roh.bed" > "$WORK/vbg.nt" 2>/dev/null
        if cmp -s "$WORK/vt.nt" "$WORK/vbg.nt"; then ok
        else bad "a BGZF VCF gave different calls than the TPED"; fi
    else
        echo "  SKIP  bgzip VCF: bgzip not installed"
    fi
}

# ---------------------------------------------------------------------------
# 4e. Genotype qualities read from the VCF FORMAT column
# ---------------------------------------------------------------------------
# The reason --vcf --gl-type exists.  A VCF normalises PL and GL so the CALLED
# genotype's value is exactly 0, so the single value the .tgls format holds is
# 0 for every call, confident or not -- the information is in how much worse
# the alternatives are, which needs the whole array (see plToError, and the
# unit tests for the arithmetic).
#
# The fixtures put the called genotype at PL 0 and the two alternatives at 30
# and 60.  That multiset is the same whichever genotype is called, so the
# implied error rate is 1 - 1/(1 + 1e-3 + 1e-6) = 0.000999999 for EVERY
# genotype -- GQ 30 to nine significant figures.  A fixture with {0,30,30}
# would NOT be GQ 30: two comparable alternatives give 0.002, which is how I
# found my first version of this test was asserting the wrong number.
vcf_likelihoods() {
    echo "== VCF genotype qualities =="

    # PL, GL and GQ encodings of the same confidence, from the same genotypes.
    awk -F'\t' -v OFS='\t' '
    /^#/ { print; next }
    {
        $9 = "GT:PL"
        for (i = 10; i <= NF; i++) {
            gt = $i
            if (index(gt, ".") > 0) { $i = gt ":."; continue }
            d = gsub(/1/, "1", gt); gt = $i
            # 0 at the called genotype, 30 and 60 on the alternatives
            s = ""
            for (g = 0; g <= 2; g++) {
                v = (g == d ? 0 : (v30 ? 60 : 30)); if (g != d) v30 = 1
                s = s (g ? "," : "") v
            }
            v30 = 0
            $i = gt ":" s
        }
        print
    }' "$WORK/chr21.vcf" > "$WORK/pl.vcf"
    awk -F'\t' -v OFS='\t' '
    /^#/ { print; next }
    { $9 = "GT:GQ"
      for (i = 10; i <= NF; i++) $i = $i (index($i, ".") > 0 ? ":." : ":30")
      print }' "$WORK/chr21.vcf" > "$WORK/gq.vcf"
    # GL is log10 of a likelihood, so GL = -PL/10 exactly.
    awk -F'\t' -v OFS='\t' '
    /^#/ { print; next }
    { $9 = "GT:GL"
      for (i = 10; i <= NF; i++) {
          n = split($i, f, ":")
          if (f[2] == ".") { $i = f[1] ":."; continue }
          split(f[2], q, ",")
          $i = f[1] ":" (-q[1]/10) "," (-q[2]/10) "," (-q[3]/10)
      }
      print }' "$WORK/pl.vcf" > "$WORK/gl.vcf"

    LB="--build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000"
    for t in GQ PL GL; do
        f=$(echo "$t" | tr 'A-Z' 'a-z')
        # shellcheck disable=SC2086
        $GARLIC --vcf "$WORK/$f.vcf" --pop "$WORK/vcf.pop" $LB --gl-type "$t" --raw-lod \
                --out "$WORK/q$t" --quiet --force >/dev/null 2>&1
        n=$(grep -vc '^track' "$WORK/q$t.roh.bed" 2>/dev/null || echo 0)
        if [ "$n" -gt 0 ]; then ok; else bad "--gl-type $t from a VCF called no ROH"; fi
    done

    # GL = -PL/10, so those two must be bit-identical.  This is the check that
    # would catch a sign or factor-of-10 error in the GL branch.
    gz "$WORK/qPL.chr21.raw.lod.windows.gz" > "$WORK/qPL.raw" 2>/dev/null
    gz "$WORK/qGL.chr21.raw.lod.windows.gz" > "$WORK/qGL.raw" 2>/dev/null
    if cmp -s "$WORK/qPL.raw" "$WORK/qGL.raw"; then ok
    else bad "--gl-type PL and --gl-type GL disagreed on equivalent input"; fi

    # And the PL array must reproduce the GQ that encodes the same confidence,
    # to the calls.  (The raw LOD differs in the last printed digit, because
    # the error rates differ by 1e-6 relative -- 0.000999999 against 0.001.)
    grep -v '^track' "$WORK/qGQ.roh.bed" > "$WORK/qGQ.nt" 2>/dev/null
    grep -v '^track' "$WORK/qPL.roh.bed" > "$WORK/qPL.nt" 2>/dev/null
    if cmp -s "$WORK/qGQ.nt" "$WORK/qPL.nt"; then ok
    else bad "the PL array and the equivalent GQ called different ROH"; fi

    # GQ 30 IS an error rate of 0.001, so that path must equal --error 0.001.
    # shellcheck disable=SC2086
    $GARLIC --vcf "$WORK/chr21.vcf.gz" --pop "$WORK/vcf.pop" $LB --error 0.001 \
            --out "$WORK/qflat" --quiet --force >/dev/null 2>&1
    grep -v '^track' "$WORK/qflat.roh.bed" > "$WORK/qflat.nt" 2>/dev/null
    if cmp -s "$WORK/qGQ.nt" "$WORK/qflat.nt"; then ok
    else bad "--gl-type GQ with GQ 30 did not match --error 0.001"; fi

    # ---- the field-presence contract ----
    glerr() {  # $1 = pattern, $2 = label, rest = args after --vcf
        pat=$1; lbl=$2; shift 2
        # shellcheck disable=SC2086
        if "$GARLIC" "$@" --pop "$WORK/vcf.pop" $LB --out "$WORK/qe" --force 2>&1 \
                | grep -q "$pat"; then ok
        else bad "$lbl"; fi
    }
    # no quality field at all
    glerr "No genotype-quality field is present at all" "missing-field message wrong when none present" \
        --vcf "$WORK/chr21.vcf.gz" --gl-type PL
    # exactly one alternative: name it
    awk -F'\t' -v OFS='\t' '/^#/{print;next} {$9="GT:PL:DP"; for(i=10;i<=NF;i++) $i=$i":20"; print}' \
        "$WORK/pl.vcf" > "$WORK/onealt.vcf"
    glerr "use --gl-type PL instead" "missing-field message did not name the single alternative" \
        --vcf "$WORK/onealt.vcf" --gl-type GQ
    # two alternatives: list both
    awk -F'\t' -v OFS='\t' '/^#/{print;next} {
        $9="GT:PL:GL"
        for(i=10;i<=NF;i++){ n=split($i,f,":")
            if(f[2]=="."){ $i=f[1]":.:."; continue }
            split(f[2],q,","); $i=f[1]":"f[2]":"(-q[1]/10)","(-q[2]/10)","(-q[3]/10) }
        print}' "$WORK/pl.vcf" > "$WORK/twoalt.vcf"
    glerr "carries PL and GL" "missing-field message did not list both alternatives" \
        --vcf "$WORK/twoalt.vcf" --gl-type GQ
    expect_exit 2 "a missing FORMAT field exits 2" "$GARLIC" --vcf "$WORK/chr21.vcf.gz" \
        --pop "$WORK/vcf.pop" --gl-type PL --build hg18 --winsize 60 --lod-cutoff 2.5 \
        --size-bounds 500000 1000000 --out "$WORK/qe" --force

    # A called genotype with '.' for the field is an error, not a silent fall
    # back to --error: the user asked for per-genotype rates.
    awk -F'\t' -v OFS='\t' 'BEGIN{n=0} /^#/{print;next} {n++
        if(n==6) for(i=10;i<=NF;i++){ split($i,f,":"); if(index(f[1],".")==0) $i=f[1]":." }
        print}' "$WORK/pl.vcf" > "$WORK/dotpl.vcf"
    glerr "has a called genotype but no PL value" "a '.' PL on a called genotype was not an error" \
        --vcf "$WORK/dotpl.vcf" --gl-type PL

    # A PL array of the wrong length is an error naming the count.
    awk -F'\t' -v OFS='\t' 'BEGIN{n=0} /^#/{print;next} {n++
        if(n==6) for(i=10;i<=NF;i++){ split($i,f,":"); $i=f[1]":0,30" }
        print}' "$WORK/pl.vcf" > "$WORK/shortpl.vcf"
    glerr "a biallelic diploid site must have 3" "a 2-value PL was not rejected" \
        --vcf "$WORK/shortpl.vcf" --gl-type PL

    # --tgls and --vcf are alternative sources; silently ignoring --tgls would
    # leave the user believing the file was used.
    glerr "alternative sources of genotype qualities" "--tgls with --vcf was not rejected" \
        --vcf "$WORK/chr21.vcf.gz" --tgls "$EX/chr21.tgls.gz" --gl-type GQ

    # --gl-type with --vcf is a third source of error rates, so --error is no
    # longer required.  This used to exit 1 on "--error must be given".
    # shellcheck disable=SC2086
    if $GARLIC --vcf "$WORK/gq.vcf" --pop "$WORK/vcf.pop" $LB --gl-type GQ \
            --out "$WORK/qne" --quiet --force >/dev/null 2>&1; then ok
    else bad "--vcf --gl-type without --error was rejected"; fi
}

# ---------------------------------------------------------------------------
# 4f. Thread-count independence
# ---------------------------------------------------------------------------
# Nothing else in this suite passes --threads, and DEFAULT_THREADS is 1, so
# before this stage the threaded code paths -- calcLOD, assembleROH, the LD
# band and the KDE -- were exercised only in their nt==1 short-circuits.  The
# guarantee being pinned is that thread count is an implementation detail:
# every stage partitions its work into contiguous blocks and concatenates them
# in thread order, so the output must be byte-identical at any --threads.
#
# It also gives the static linux CI job real thread creation to exercise.  That
# matters because libstdc++ decides at RUNTIME whether threading is available
# by testing a weak symbol, and a static link can leave that symbol unresolved
# -- the link succeeds and the first std::thread constructor throws.  Without a
# case that actually spawns a thread, a static build would pass this suite
# while being unable to run threaded at all.
threads() {
    echo "== thread-count independence"

    for spec in \
        "unweighted|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz" \
        "weighted|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --map $EX/chr21.map.gz --weighted" \
        "phased|--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --phased"
    do
        lbl=${spec%%|*}
        args=${spec#*|}
        for t in 1 4; do
            # shellcheck disable=SC2086
            $GARLIC $args --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 \
                    --size-bounds 500000 1000000 --raw-lod --threads $t \
                    --out "$WORK/th_${lbl}_$t" --quiet --force >/dev/null 2>&1
        done
        if [ ! -f "$WORK/th_${lbl}_1.roh.bed" ] || [ ! -f "$WORK/th_${lbl}_4.roh.bed" ]; then
            bad "$lbl: a --threads run produced no output"
            continue
        fi
        n=$(grep -v '^track' "$WORK/th_${lbl}_1.roh.bed" | wc -l | tr -d ' ')
        if [ "$n" -eq 0 ]; then
            bad "$lbl: called 0 ROH -- the thread comparison would be vacuous"
            continue
        fi
        if cmp -s "$WORK/th_${lbl}_1.roh.bed" "$WORK/th_${lbl}_4.roh.bed"; then ok
        else bad "$lbl: --threads 1 and --threads 4 gave different calls"; fi

        # the raw LOD matrix is the stronger comparison: it comes straight out
        # of the threaded stage, before windows are assembled into tracts.
        gz "$WORK/th_${lbl}_1.chr21.raw.lod.windows.gz" > "$WORK/th_${lbl}_1.raw"
        gz "$WORK/th_${lbl}_4.chr21.raw.lod.windows.gz" > "$WORK/th_${lbl}_4.raw"
        if cmp -s "$WORK/th_${lbl}_1.raw" "$WORK/th_${lbl}_4.raw"; then ok
        else bad "$lbl: raw LOD scores differ between --threads 1 and 4"; fi
    done

    # The KDE is threaded too, and only the automatic-cutoff path reaches it.
    for t in 1 4; do
        # shellcheck disable=SC2086
        $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 \
                --winsize 60 --error 0.001 --threads $t \
                --out "$WORK/thk_$t" --quiet --force >/dev/null 2>&1
    done
    a=$(grep -oE 'Selected LOD score cutoff: [-0-9.e+]+' "$WORK/thk_1.log" 2>/dev/null | awk '{print $5}')
    b=$(grep -oE 'Selected LOD score cutoff: [-0-9.e+]+' "$WORK/thk_4.log" 2>/dev/null | awk '{print $5}')
    if [ -n "$a" ] && [ "$a" = "$b" ]; then ok
    else bad "KDE cutoff depends on --threads ($a vs $b)"; fi

    # The size-class GMM is fed the per-individual ROH lengths concatenated in
    # THREAD ORDER, so its boundaries are the check on that concatenation.  The
    # three cases above pass --size-bounds and therefore skip the GMM entirely;
    # this run does not, which is the only place the ordering is covered.
    a=$(grep -oE 'Selected ROH size boundaries.*' "$WORK/thk_1.log" 2>/dev/null)
    b=$(grep -oE 'Selected ROH size boundaries.*' "$WORK/thk_4.log" 2>/dev/null)
    if [ -n "$a" ] && [ "$a" = "$b" ]; then ok
    else bad "GMM size boundaries depend on --threads ($a vs $b)"; fi
}

# ---------------------------------------------------------------------------
# 4g. --outdir
# ---------------------------------------------------------------------------
# makeOutdir had no coverage at all until the MinGW build failed on it: POSIX
# mkdir takes (path, mode) and the Windows CRT takes (path) only, so the call
# did not compile there.  A function that needs an #ifdef needs a test.
outdir_paths() {
    echo "== --outdir =="
    OD=$WORK/outdir; mkdir -p "$OD"
    A="--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000"
    # shellcheck disable=SC2086
    "$GARLIC" $A --out "$OD/plain" --force >/dev/null 2>&1

    # a nested path is created in full, and produces the same calls
    # shellcheck disable=SC2086
    "$GARLIC" $A --outdir "$OD/a/b/c" --out r --force >/dev/null 2>&1
    if [ -f "$OD/a/b/c/r.roh.bed" ]; then ok; else bad "--outdir did not create a/b/c"; fi
    if cmp -s "$OD/a/b/c/r.roh.bed" "$OD/plain.roh.bed"; then ok
    else bad "--outdir output differs from the same run without it"; fi

    # an existing directory is not an error (mkdir returns EEXIST)
    # shellcheck disable=SC2086
    expect_exit 0 "--outdir onto an existing directory" \
        "$GARLIC" $A --outdir "$OD/a/b/c" --out r --force

    # a trailing separator
    # shellcheck disable=SC2086
    "$GARLIC" $A --outdir "$OD/trail/" --out r --force >/dev/null 2>&1
    if [ -f "$OD/trail/r.roh.bed" ]; then ok; else bad "--outdir with a trailing / failed"; fi

    # a path that cannot be created is a usage error, not a crash and not a
    # silent write into the working directory
    # shellcheck disable=SC2086
    # A path that cannot be created is a usage error, not a crash and not a
    # silent write into the working directory.
    #
    # Windows takes a native path here rather than the POSIX one, and that is
    # the point.  Passing "$OD/plain.roh.bed/sub" to a native binary from an
    # MSYS2 shell does not reach it intact: three runs of this case reported
    #
    #     garlic resolved: Output file basename: /tmp/.../plain.roh.bed/sub/r
    #
    # i.e. the raw POSIX string, which the Windows CRT then resolves relative
    # to the current drive -- a fresh, creatable chain that the shell's view of
    # $WORK does not contain, so garlic succeeded and its output vanished.
    # MSYS2 converted the neighbouring arguments ("$OD/a/b/c", and "$OD/plain.roh.bed"
    # itself) correctly; the one it passed through is the one whose parent
    # component is a regular FILE, which is what a converter resolving the
    # longest existing prefix would choke on.  cygpath sidesteps the converter
    # so the case tests garlic rather than the harness.
    f0=$fail
    UNCREATABLE="$OD/plain.roh.bed/sub"
    case "$(uname -s)" in
        MINGW*|MSYS*|CYGWIN*)
            # Without cygpath the substitution would be empty and UNCREATABLE
            # would become "\plain.roh.bed\sub" -- a drive-relative path garlic
            # can create, so the case would report something meaningless rather
            # than nothing.  Skip instead.
            if command -v cygpath >/dev/null 2>&1; then
                UNCREATABLE="$(cygpath -w "$OD")\\plain.roh.bed\\sub"
            else
                echo "  SKIP  --outdir onto an uncreatable path: cygpath not available"
                UNCREATABLE=""
            fi
            ;;
    esac
    if [ -n "$UNCREATABLE" ]; then
        # shellcheck disable=SC2086
        expect_exit 1 "--outdir onto an uncreatable path" \
            "$GARLIC" $A --outdir "$UNCREATABLE" --out r --force
        if [ "$fail" -ne "$f0" ]; then
            echo "        requested: $UNCREATABLE"
            printf '        plain.roh.bed: '; ls -ld "$OD/plain.roh.bed" 2>&1 | head -1
            printf '        sub:           '; ls -ld "$OD/plain.roh.bed/sub" 2>&1 | head -1
            found=$(find "$WORK" -name 'r.roh.bed' 2>/dev/null | tr '\n' ' ')
            echo "        r.roh.bed under \$WORK: ${found:-nowhere}"
            [ -f ./r.roh.bed ] && echo "        also in the cwd: --outdir was ignored entirely"
            # garlic logs the basename it resolved, but --quiet suppresses it.  Re-run
            # without --quiet and read it back: that names the path it actually used,
            # which is the one fact the exit status cannot give.
            # shellcheck disable=SC2086
            "$GARLIC" $A --outdir "$UNCREATABLE" --out r --force 2>&1 \
                | grep -i "output file basename" | head -1 | sed 's/^/        garlic resolved: /'
        fi
    fi

    # An output basename whose directory does not exist is a runtime error with
    # a message, not a crash.  errlog opens <out>.log lazily in commit(), threw
    # 0 there, and nothing caught it: this used to die with "terminating due to
    # uncaught exception of type int" and SIGABRT (exit 134) after validating
    # every argument.  Uses a missing directory rather than an unwritable one,
    # because chmod does not restrict the owner on Windows.
    # shellcheck disable=SC2086
    expect_exit 2 "--out into a directory that does not exist" \
        "$GARLIC" $A --out "$OD/no/such/dir/r" --force

    # ...and neither is a path that exists as a FILE.  mkdir returns EEXIST for
    # that, which garlic used to accept before aborting in the writers (exit
    # 134 on POSIX, and on Windows it made the case above look like success).
    # shellcheck disable=SC2086
    expect_exit 1 "--outdir onto an existing file" \
        "$GARLIC" $A --outdir "$OD/plain.roh.bed" --out r --force

    # Text output must be LF on every platform: the Windows CRT turns \n into
    # \r\n in text mode, which made every golden .roh.bed and .froh.tsv differ
    # on MinGW while being otherwise byte-identical.  The writers open with
    # ios::binary; this checks the bytes rather than trusting that.
    # Counted, not read: `read` returns nonzero at EOF even when it consumed
    # bytes, so a CRLF file would have passed a `! ... | read` test.
    crs=$(tr -dc '\r' < "$OD/plain.roh.bed" | wc -c | tr -d ' ')
    if [ "$crs" = "0" ]; then ok
    else bad "output has $crs carriage returns: a writer is not in binary mode"; fi

    # On POSIX a backslash is an ordinary filename character and must NOT split
    # the path; on Windows it is a separator.  Test whichever applies.
    case "$(uname -s)" in
        MINGW*|MSYS*|CYGWIN*)
            # shellcheck disable=SC2086
            "$GARLIC" $A --outdir "$OD/w1\\w2" --out r --force >/dev/null 2>&1
            if [ -f "$OD/w1/w2/r.roh.bed" ]; then ok
            else bad "backslash was not treated as a separator on Windows"; fi
            ;;
        *)
            # shellcheck disable=SC2086
            "$GARLIC" $A --outdir "$OD/one\\two" --out r --force >/dev/null 2>&1
            if [ -f "$OD/one\\two/r.roh.bed" ]; then ok
            else bad "backslash should be one directory name on POSIX"; fi
            ;;
    esac
}

# ---------------------------------------------------------------------------
# 4h. --freq-file format
# ---------------------------------------------------------------------------
# The frequency file is WIDE: one row per locus, one frequency column per
# population, named in the header after ALLELE.  Wide rather than one row per
# (locus, population) because ALLELE orients the frequency and belongs to the
# SITE -- one ALLELE column makes it impossible for two populations to
# disagree about the orientation of a locus.
#
# Only the CLI-reachable cases are here.  Matching a population to its column
# by NAME is covered where it becomes reachable, once populations are analysed
# separately; until then this run has one pooled analysis and asks for one
# column.
freq_file_format() {
    echo "== --freq-file format =="
    FF=$WORK/ff; mkdir -p "$FF"
    A="--tped $EX/chr21.tped.gz --tfam $EX/chr21.tfam.gz --build hg18 --winsize 60
       --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000"

    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 \
        --error 0.001 --freq-only --out "$FF/base" --quiet --force >/dev/null 2>&1

    # the five-column file garlic writes must read back unchanged
    # shellcheck disable=SC2086
    "$GARLIC" $A --freq-file "$FF/base.freq.gz" --out "$FF/legacy" --quiet --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    "$GARLIC" $A --out "$FF/nofreq" --quiet --force >/dev/null 2>&1
    if [ -s "$FF/legacy.roh.bed" ]; then ok
    else bad "a five-column frequency file no longer reads"; fi

    # the single column applies whatever it is called: files predating any
    # population naming must keep working, so the name is not checked when
    # there is only one.
    gzip -cd "$FF/base.freq.gz" | sed '1s/FREQ/MAF/' | gzip > "$FF/maf.freq.gz"
    # shellcheck disable=SC2086
    "$GARLIC" $A --freq-file "$FF/maf.freq.gz" --out "$FF/maf" --quiet --force >/dev/null 2>&1
    if [ -s "$FF/maf.roh.bed" ] && cmp -s "$FF/maf.roh.bed" "$FF/legacy.roh.bed"; then ok
    else bad "a single frequency column named something other than FREQ changed the result"; fi

    # a wide file has no meaning for a run that analyses every sample as one:
    # there is no correct column to choose, so it is an error rather than a
    # silent pick.
    gzip -cd "$FF/base.freq.gz" | awk 'NR==1{print $0"\tPOPB"} NR>1{print $0"\t"$5}' \
        | gzip > "$FF/wide.freq.gz"
    # shellcheck disable=SC2086
    expect_exit 2 "a multi-population frequency file in a pooled run" \
        "$GARLIC" $A --freq-file "$FF/wide.freq.gz" --out "$FF/wide" --force

    # a header too short to name its columns
    gzip -cd "$FF/base.freq.gz" | sed '1s/.*/CHR\tSNP\tPOS/' | gzip > "$FF/shorthdr.freq.gz"
    # shellcheck disable=SC2086
    expect_exit 2 "a frequency file whose header has fewer than five fields" \
        "$GARLIC" $A --freq-file "$FF/shorthdr.freq.gz" --out "$FF/sh" --force
}

# ---------------------------------------------------------------------------
# 4i. Half calls
# ---------------------------------------------------------------------------
# A HALF call -- one allele observed, one missing ("A 0" in a TPED, "0/." in a
# VCF) -- is unusable as a genotype, but the allele that WAS observed is real.
# loadTPEDData has always counted it towards the allele frequency while storing
# the genotype as missing; the VCF path used to discard it, so the two input
# paths disagreed.  They now agree.
#
# The fixture is hand sized so the two rules give visibly different numbers.
# Four individuals at one locus: A/A, A/G, G/G, A/. with A counted.
#     counting the observed allele:  4 of 7  = 0.571429
#     discarding the half call:      3 of 6  = 0.5
# and through the VCF with REF=A ALT=G, where ALT is counted:
#     counting:                      3 of 7  = 0.428571
#     discarding:                    3 of 6  = 0.5
# So the two frequencies must be COMPLEMENTARY.  Under the old behaviour the
# VCF gave 0.5 and they summed to 1.071429.
half_calls() {
    echo "== half calls =="
    HC=$WORK/hc; mkdir -p "$HC"

    # ONE population: column 1 of a TFAM is garlic's population label, so four
    # distinct values here would be four one-individual populations, and the
    # outputs would be named <out>.<POP>.roh.bed rather than <out>.roh.bed.
    printf 'P\ti1\t0\t0\t0\t0\nP\ti2\t0\t0\t0\t0\nP\ti3\t0\t0\t0\t0\nP\ti4\t0\t0\t0\t0\n' > "$HC/h.tfam"
    # rsHALF carries the half call; the rest exist only so a window can form
    # (--winsize must be > 1).
    {
      printf 'chr21\trsHALF\t0\t9411000\tA\tA\tA\tG\tG\tG\tA\t0\n'
      printf 'chr21\trsB\t0\t9412000\tC\tC\tC\tT\tT\tT\tC\tC\n'
      printf 'chr21\trsC\t0\t9413000\tG\tG\tG\tG\tA\tA\tG\tA\n'
      printf 'chr21\trsD\t0\t9414000\tT\tT\tT\tC\tC\tC\tT\tT\n'
    } > "$HC/h.tped"

    {
      printf '##fileformat=VCFv4.2\n'
      printf '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
      printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\ti1\ti2\ti3\ti4\n'
      printf 'chr21\t9411000\trsHALF\tA\tG\t.\tPASS\t.\tGT\t0/0\t0/1\t1/1\t0/.\n'
      printf 'chr21\t9412000\trsB\tC\tT\t.\tPASS\t.\tGT\t0/0\t0/1\t1/1\t0/0\n'
      printf 'chr21\t9413000\trsC\tG\tA\t.\tPASS\t.\tGT\t0/0\t0/0\t1/1\t0/1\n'
      printf 'chr21\t9414000\trsD\tT\tC\t.\tPASS\t.\tGT\t0/0\t0/1\t1/1\t0/0\n'
    } > "$HC/h.vcf"
    printf 'i1\tP\ni2\tP\ni3\tP\ni4\tP\n' > "$HC/h.pop"

    "$GARLIC" --tped "$HC/h.tped" --tfam "$HC/h.tfam" --build hg18 --error 0.001 \
        --freq-only --out "$HC/t" --quiet --force >/dev/null 2>&1
    "$GARLIC" --vcf "$HC/h.vcf" --pop "$HC/h.pop" --build hg18 --error 0.001 \
        --freq-only --out "$HC/v" --quiet --force >/dev/null 2>&1

    ft=$(gzip -cd "$HC/t.freq.gz" 2>/dev/null | awk 'NR==2{print $5}')
    fv=$(gzip -cd "$HC/v.freq.gz" 2>/dev/null | awk 'NR==2{print $5}')

    # the TPED rule, unchanged: 4 of 7 observed alleles
    if [ "$ft" = "0.571429" ]; then ok
    else bad "TPED half call: frequency $ft, expected 0.571429 (4 of 7 observed alleles)"; fi

    # the VCF must now follow it: 3 of 7, counting ALT.  0.5 here means the
    # half call was discarded, which is the behaviour this replaced.
    if [ "$fv" = "0.428571" ]; then ok
    else bad "VCF half call: frequency $fv, expected 0.428571 (3 of 7); 0.5 means the observed allele was discarded"; fi

    # stated as the property rather than the two numbers: the paths count the
    # same alleles, in opposite orientations
    sum=$(awk -v a="$ft" -v b="$fv" 'BEGIN{printf "%.6f", a+b}')
    if [ "$sum" = "1.000000" ]; then ok
    else bad "TPED and VCF frequencies do not reconcile: $ft + $fv = $sum"; fi

    # and the genotype is still missing: a half call must not be scored.  With
    # every individual either missing or called, a run over this one locus must
    # not crash and must produce no tract.
    # every locus must reconcile, not just the one with the half call
    # Two files and a two-file awk, not `paste <(...) <(...)`: process
    # substitution is a bashism and this suite runs under POSIX sh, where it
    # produced an empty count that read as a failure.
    gzip -cd "$HC/t.freq.gz" | awk 'NR>1{print $5}' > "$HC/tf"
    gzip -cd "$HC/v.freq.gz" | awk 'NR>1{print $5}' > "$HC/vf"
    recon=$(awk 'NR==FNR{a[FNR]=$1; next}
                 {d=a[FNR]+$1-1; if (d<0) d=-d; if (d>1e-6) bad++}
                 END{print bad+0}' "$HC/tf" "$HC/vf")
    if [ "$recon" = "0" ]; then ok
    else bad "$recon loci do not reconcile between the TPED and VCF paths"; fi

    # the genotype is still missing: a half call must not be scored, and a
    # dataset containing one must run.
    "$GARLIC" --tped "$HC/h.tped" --tfam "$HC/h.tfam" --build hg18 --winsize 2 \
        --error 0.001 --lod-cutoff 2.5 --size-bounds 100 200 \
        --out "$HC/roh" --quiet --force >/dev/null 2>&1
    if [ -f "$HC/roh.roh.bed" ]; then ok
    else bad "a dataset containing a half call failed to run"; fi
}

# ---------------------------------------------------------------------------
# 4j. Multiple populations
# ---------------------------------------------------------------------------
# Several populations in one run are analysed SEPARATELY: each gets allele
# frequencies, a LOD cutoff and size classes from its own individuals, and its
# own output files.  Anything given explicitly on the command line is not
# re-derived, so it applies to every population.
#
# The fixture relabels the tracked chr21 TFAM into two halves, so no new data
# is needed and the genotypes are the ones every other stage uses.
multi_population() {
    echo "== multiple populations =="
    MP=$WORK/mp; mkdir -p "$MP"
    gz "$EX/chr21.tped.gz" > "$MP/two.tped"
    gz "$EX/chr21.tfam.gz" | awk 'BEGIN{OFS="\t"} {$1 = (NR<=22 ? "POPA" : "POPB"); print}' > "$MP/two.tfam"
    A="--build hg18 --winsize 60 --error 0.001"

    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --froh \
        --out "$MP/both" --quiet --force >/dev/null 2>&1

    # named per population, and NOT under the bare basename
    if [ -f "$MP/both.POPA.roh.bed" ] && [ -f "$MP/both.POPB.roh.bed" ]; then ok
    else bad "a two-population run did not write <out>.<POP>.roh.bed for both"; fi
    if [ ! -f "$MP/both.roh.bed" ]; then ok
    else bad "a two-population run also wrote the unlabelled <out>.roh.bed"; fi
    if [ -f "$MP/both.POPA.froh.tsv" ] && [ -f "$MP/both.POPB.froh.tsv" ]; then ok
    else bad "--froh did not follow the per-population naming"; fi

    # each population contains only its own individuals
    na=$(grep -c '^track' "$MP/both.POPA.roh.bed" 2>/dev/null || echo 0)
    nb=$(grep -c '^track' "$MP/both.POPB.roh.bed" 2>/dev/null || echo 0)
    if [ "$na" -eq 22 ] && [ "$nb" -eq 23 ]; then ok
    else bad "per-population tracks: POPA $na (expected 22), POPB $nb (expected 23)"; fi

    # the analysis really was separate: two populations of the same data at the
    # same window size must not land on the same automatically chosen cutoff
    ca=$(grep -o '"lod_cutoff": [^,}]*' "$MP/both.POPA.params.json" 2>/dev/null | head -1)
    cb=$(grep -o '"lod_cutoff": [^,}]*' "$MP/both.POPB.params.json" 2>/dev/null | head -1)
    if [ -n "$ca" ] && [ "$ca" != "$cb" ]; then ok
    else bad "both populations selected the same LOD cutoff ($ca); the analysis may not be separate"; fi

    # each run record names its population and carries its own derived seed
    sa=$(grep -o '"population_seed": [0-9]*' "$MP/both.POPA.params.json" 2>/dev/null)
    sb=$(grep -o '"population_seed": [0-9]*' "$MP/both.POPB.params.json" 2>/dev/null)
    if [ -n "$sa" ] && [ "$sa" != "$sb" ]; then ok
    else bad "the two populations share a derived seed ($sa)"; fi

    # the record must be valid JSON.  --load-params parses it, which is a
    # stronger check than grep: an unquoted population label passed grep and
    # broke every JSON reader.
    # shellcheck disable=SC2086
    "$GARLIC" --load-params "$MP/both.POPA.params.json" --tped "$MP/two.tped" \
        --tfam "$MP/two.tfam" --out "$MP/rt" --quiet --force >/dev/null 2>&1
    if [ -f "$MP/rt.POPA.roh.bed" ]; then ok
    else bad "a per-population params.json could not be read back with --load-params"; fi

    # an explicit value is NOT re-derived per population: both must use it
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --lod-cutoff 2.5 \
        --size-bounds 500000 1000000 --out "$MP/fixed" --quiet --force >/dev/null 2>&1
    fa=$(grep -o '"lod_cutoff": [^,}]*' "$MP/fixed.POPA.params.json" 2>/dev/null | head -1)
    fb=$(grep -o '"lod_cutoff": [^,}]*' "$MP/fixed.POPB.params.json" 2>/dev/null | head -1)
    if [ "$fa" = '"lod_cutoff": 2.5' ] && [ "$fb" = '"lod_cutoff": 2.5' ]; then ok
    else bad "--lod-cutoff did not apply to both populations: POPA $fa, POPB $fb"; fi

    # THE acceptance property: a population analysed alongside another must get
    # exactly what it gets alone.  That holds only because filtering is now per
    # population -- a site monomorphic in POPA but polymorphic in POPB used to
    # be retained for POPA, giving it windows it would never have had alone.
    # 22 individuals in POPA, 23 in POPB; TPED has 4 metadata columns then 2 per
    # individual, so POPA is fields 5..48 and POPB is 49..94.
    awk 'BEGIN{OFS="\t"} {printf "%s\t%s\t%s\t%s", $1,$2,$3,$4; for(i=5;i<=48;i++) printf "\t%s", $i; printf "\n"}' \
        "$MP/two.tped" > "$MP/onlyA.tped"
    awk 'BEGIN{OFS="\t"} {printf "%s\t%s\t%s\t%s", $1,$2,$3,$4; for(i=49;i<=94;i++) printf "\t%s", $i; printf "\n"}' \
        "$MP/two.tped" > "$MP/onlyB.tped"
    head -22 "$MP/two.tfam" > "$MP/onlyA.tfam"
    tail -23 "$MP/two.tfam" > "$MP/onlyB.tfam"
    for POP in A B; do
        # shellcheck disable=SC2086
        "$GARLIC" --tped "$MP/only$POP.tped" --tfam "$MP/only$POP.tfam" $A --froh \
            --out "$MP/alone$POP" --quiet --force >/dev/null 2>&1
        if cmp -s "$MP/alone$POP.roh.bed" "$MP/both.POP$POP.roh.bed"; then ok
        else bad "POP$POP analysed alongside another differs from POP$POP analysed alone"; fi
        if cmp -s "$MP/alone$POP.froh.tsv" "$MP/both.POP$POP.froh.tsv"; then ok
        else bad "POP$POP --froh differs between the joint and the solo run"; fi
    done

    # --freq-file carries one column per population, matched BY NAME, so the
    # column order does not have to match the order populations appear in the
    # TFAM.  The file here is written POPB first for exactly that reason.
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" --build hg18 --error 0.001 \
        --freq-only --out "$MP/ff" --quiet --force >/dev/null 2>&1
    gz "$MP/ff.freq.gz" | awk 'BEGIN{OFS="\t"}
        NR==1{print $1,$2,$3,$4,"POPB","POPA"; next}
        {print $1,$2,$3,$4,1-$5,$5}' > "$MP/wide.freq"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --freq-file "$MP/wide.freq" \
        --out "$MP/wf" --quiet --force >/dev/null 2>&1
    # POPA's column is the pooled frequency, so POPA alone with just that column
    # must reproduce POPA inside the joint run
    gz "$MP/ff.freq.gz" | awk 'BEGIN{OFS="\t"}
        NR==1{print $1,$2,$3,$4,"POPA"; next} {print $1,$2,$3,$4,$5}' > "$MP/justA.freq"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/onlyA.tped" --tfam "$MP/onlyA.tfam" $A --freq-file "$MP/justA.freq" \
        --out "$MP/sA" --quiet --force >/dev/null 2>&1
    if cmp -s "$MP/sA.roh.bed" "$MP/wf.POPA.roh.bed"; then ok
    else bad "a population did not use its own column of a multi-population frequency file"; fi

    # a column missing for one of the populations names it
    gz "$MP/ff.freq.gz" | awk 'BEGIN{OFS="\t"}
        NR==1{print $1,$2,$3,$4,"POPZ","POPA"; next}
        {print $1,$2,$3,$4,1-$5,$5}' > "$MP/miss.freq"
    # shellcheck disable=SC2086
    if "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --freq-file "$MP/miss.freq" \
            --out "$MP/msf" --quiet --force 2>&1 | grep -q "no frequency column for population POPB"; then ok
    else bad "a frequency file missing one population's column did not name it"; fi
    # shellcheck disable=SC2086
    expect_exit 2 "a frequency file missing a population's column exits 2" \
        "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A \
        --freq-file "$MP/miss.freq" --out "$MP/msf2" --force

    # a ONE-column file is the legacy format and still applies to everything,
    # so an existing .freq.gz keeps working when the run gains populations
    gz "$MP/ff.freq.gz" > "$MP/legacy.freq"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --freq-file "$MP/legacy.freq" \
        --out "$MP/lg" --quiet --force >/dev/null 2>&1
    if [ -f "$MP/lg.POPA.roh.bed" ] && [ -f "$MP/lg.POPB.roh.bed" ]; then ok
    else bad "a one-column frequency file was refused for a multi-population run"; fi

    # --pool-populations ignores the labels and analyses everyone together,
    # which is what garlic did before.  Checked INTRINSICALLY rather than
    # against an old binary: pooling a two-population file must give exactly
    # what the same genotypes give under a one-population TFAM, because that
    # is the same computation on the same individuals.
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --froh --pool-populations \
        --out "$MP/pooled" --quiet --force >/dev/null 2>&1
    gz "$EX/chr21.tfam.gz" > "$MP/one.tfam"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/one.tfam" $A --froh \
        --out "$MP/asone" --quiet --force >/dev/null 2>&1
    # The CALLS must match.  The track lines and the froh 'pop' column carry
    # the labels, which genuinely differ between the two TFAMs -- that is the
    # inputs disagreeing about names, not the analyses disagreeing about ROH.
    if cmp -s "$(grep -v '^track' "$MP/pooled.roh.bed" > "$MP/pc.bed"; echo "$MP/pc.bed")" \
              "$(grep -v '^track' "$MP/asone.roh.bed" > "$MP/ac.bed"; echo "$MP/ac.bed")"; then ok
    else bad "--pool-populations did not reproduce the single-population ROH calls"; fi
    # Every column except the pop label, which is the one thing allowed to
    # differ.  Listing the columns by number silently stopped comparing the
    # rest of the table when FROH went wide.
    cut -f1,3- "$MP/pooled.froh.tsv" | grep -v '^##' > "$MP/pf.tsv"
    cut -f1,3- "$MP/asone.froh.tsv" | grep -v '^##' > "$MP/af.tsv"
    if cmp -s "$MP/pf.tsv" "$MP/af.tsv"; then ok
    else bad "--pool-populations --froh differs from the single-population run"; fi
    # the labels themselves must follow the TFAM, which is what makes the
    # comparison above a comparison of calls rather than of names
    if [ "$(cut -f2 "$MP/pooled.froh.tsv" | grep -c POPA)" -gt 0 ]; then ok
    else bad "a pooled run lost the population labels from its froh table"; fi

    # and it restores the old output names
    if [ -f "$MP/pooled.roh.bed" ] && [ ! -f "$MP/pooled.POPA.roh.bed" ]; then ok
    else bad "--pool-populations did not restore the unlabelled output names"; fi

    # the record still reports which populations were present, and marks the
    # pooling -- otherwise a pooled run is indistinguishable from a file that
    # really had one population
    if grep -q '"populations_pooled": true' "$MP/pooled.params.json" &&
       grep -q '"populations": \["POPA", "POPB"\]' "$MP/pooled.params.json"; then ok
    else bad "a pooled run's record does not mark the pooling or list the populations"; fi

    # pooling several populations biases the frequencies, and says so
    # shellcheck disable=SC2086
    if "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --pool-populations \
            --out "$MP/pw" --force 2>&1 | grep -q "pools allele frequencies across 2 populations"; then ok
    else bad "--pool-populations did not warn that frequencies are pooled"; fi

    # on a file that really has one population the flag is a no-op
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/one.tfam" $A --froh --pool-populations \
        --out "$MP/p1" --quiet --force >/dev/null 2>&1
    if cmp -s "$MP/p1.roh.bed" "$MP/asone.roh.bed"; then ok
    else bad "--pool-populations changed a single-population run"; fi

    # The run's own frequency file is written in the format --freq-file reads,
    # one column per population, so feeding it back reproduces the run.  A
    # single pooled column would describe an analysis that did not happen.
    if gz "$MP/both.freq.gz" | head -1 | grep -q 'ALLELE.*POPA.*POPB'; then ok
    else bad "a multi-population run did not write a per-population frequency file"; fi
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --froh \
        --freq-file "$MP/both.freq.gz" --out "$MP/rtf" --quiet --force >/dev/null 2>&1
    if cmp -s "$MP/rtf.POPA.roh.bed" "$MP/both.POPA.roh.bed" &&
       cmp -s "$MP/rtf.POPB.roh.bed" "$MP/both.POPB.roh.bed"; then ok
    else bad "a run's own frequency file did not reproduce the run"; fi

    # A pooled table has to be distinguishable from a per-population one once
    # it is separated from the run.  The pop COLUMN already names the
    # population in a per-population table, so only the pooled case needs a
    # header -- and adding one to the per-population case would make a
    # population's table depend on what it was run alongside.
    if grep -q '^## populations_pooled	true' "$MP/pooled.froh.tsv" &&
       ! grep -q 'populations_pooled' "$MP/both.POPA.froh.tsv"; then ok
    else bad "the froh table does not mark pooling, or marks it when not pooled"; fi

    # A population that cannot be analysed must say WHICH, and stop the run:
    # a partial result set that looks complete is the worse failure.
    # shellcheck disable=SC2086
    if "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 99999 --out "$MP/fail" --force 2>&1 \
            | grep -q '\[population POPA\] Cannot fit'; then ok
    else bad "a population that failed size-class fitting was not named"; fi
    if [ ! -f "$MP/fail.POPB.roh.bed" ]; then ok
    else bad "a failed population did not stop the run"; fi
    # shellcheck disable=SC2086
    expect_exit 2 "a failed population exits 2" \
        "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" --build hg18 --winsize 60 \
        --error 0.001 --lod-cutoff 99999 --out "$MP/fail2" --force
    # and the single-population wording is untouched: no label, same capital
    # shellcheck disable=SC2086
    if "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/one.tfam" --build hg18 --winsize 60 \
            --error 0.001 --lod-cutoff 99999 --out "$MP/fail3" --force 2>&1 \
            | grep -q 'ERROR: Cannot fit a'; then ok
    else bad "the single-population failure message changed"; fi

    # --freq-only streams the input rather than loading it, so it is a SECOND
    # implementation of the allele-frequency rule.  With several populations it
    # writes the same wide file, and the two must agree exactly -- if they ever
    # drift, one of them is wrong.
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" --build hg18 --error 0.001 \
        --freq-only --out "$MP/fo" --quiet --force >/dev/null 2>&1
    if gz "$MP/fo.freq.gz" | head -1 | grep -q 'ALLELE.*POPA.*POPB'; then ok
    else bad "--freq-only did not write a per-population frequency file"; fi
    if cmp -s "$(gz "$MP/fo.freq.gz" > "$MP/fo.txt"; echo "$MP/fo.txt")" \
              "$(gz "$MP/both.freq.gz" > "$MP/bo.txt"; echo "$MP/bo.txt")"; then ok
    else bad "--freq-only and the full pipeline disagree about the frequencies"; fi

    # and it feeds straight back
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" $A --freq-file "$MP/fo.freq.gz" \
        --out "$MP/fort" --quiet --force >/dev/null 2>&1
    if cmp -s "$MP/fort.POPA.roh.bed" "$MP/both.POPA.roh.bed"; then ok
    else bad "a --freq-only file did not reproduce the run"; fi

    # --pool-populations asks for the single pooled column, whatever the labels
    # say -- the same escape hatch as for the analysis itself.
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/two.tfam" --build hg18 --error 0.001 \
        --freq-only --pool-populations --out "$MP/fop" --quiet --force >/dev/null 2>&1
    if gz "$MP/fop.freq.gz" | head -1 | grep -q 'ALLELE.FREQ$'; then ok
    else bad "--freq-only --pool-populations did not write a single pooled column"; fi
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/one.tfam" --build hg18 --error 0.001 \
        --freq-only --out "$MP/fo1" --quiet --force >/dev/null 2>&1
    if cmp -s "$(gz "$MP/fop.freq.gz" > "$MP/fop.txt"; echo "$MP/fop.txt")" \
              "$(gz "$MP/fo1.freq.gz" > "$MP/fo1.txt"; echo "$MP/fo1.txt")"; then ok
    else bad "--freq-only --pool-populations differs from the single-population run"; fi

    # --pop supplies the labels, and --pool-populations still overrides them
    cut -f2 "$MP/two.tfam" | awk '{print $1"\t"(NR<=22?"PX":"PY")}' > "$MP/lab.pop"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/one.tfam" --pop "$MP/lab.pop" --build hg18 \
        --error 0.001 --freq-only --out "$MP/fpop" --quiet --force >/dev/null 2>&1
    if gz "$MP/fpop.freq.gz" | head -1 | grep -q 'ALLELE.*PX.*PY'; then ok
    else bad "--pop did not reach --freq-only"; fi
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/one.tfam" --pop "$MP/lab.pop" --build hg18 \
        --error 0.001 --freq-only --pool-populations --out "$MP/fpopp" --quiet --force >/dev/null 2>&1
    if gz "$MP/fpopp.freq.gz" | head -1 | grep -q 'ALLELE.FREQ$'; then ok
    else bad "--pool-populations did not override --pop under --freq-only"; fi

    # one population keeps the unlabelled names, so nothing existing changes
    gz "$EX/chr21.tfam.gz" > "$MP/one.tfam"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$MP/two.tped" --tfam "$MP/one.tfam" $A --lod-cutoff 2.5 \
        --size-bounds 500000 1000000 --out "$MP/one" --quiet --force >/dev/null 2>&1
    if [ -f "$MP/one.roh.bed" ] && [ ! -f "$MP/one.POPA.roh.bed" ]; then ok
    else bad "a single-population run did not use the unlabelled output names"; fi
}

# ---------------------------------------------------------------------------
# 5. Round trip through --load-params
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# 4m. Sex chromosomes
# ---------------------------------------------------------------------------
# No shipped file exercises any of this -- the bundled example is chromosomes
# 1-22 -- so every fixture is derived here from chr21 by relabelling column 1.
# The genotypes are unchanged, which is what makes the --sex-system none case
# a byte-for-byte comparison against the ordinary chr21 run.
sex_chromosomes() {
    echo "== sex chromosomes =="
    SEXBASE="--build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000"

    gz "$EX/chr21.tped.gz" | sed 's/^21/chrX/'  | gzip > "$WORK/sxX.tped.gz"
    gz "$EX/chr21.tped.gz" | sed 's/^21/chrZ/'  | gzip > "$WORK/sxZ.tped.gz"
    gz "$EX/chr21.tped.gz" | sed 's/^21/23/'    | gzip > "$WORK/sx23.tped.gz"
    gz "$EX/chr21.tped.gz" | sed 's/^21/chrM/'  | gzip > "$WORK/sxM.tped.gz"
    # Mixed autosome + chrX, in that order.
    { gz "$EX/chr21.tped.gz"; gz "$WORK/sxX.tped.gz"; } | gzip > "$WORK/sxmix.tped.gz"
    # Two spellings of one chromosome: 21 and chr21.
    { gz "$EX/chr21.tped.gz"; gz "$EX/chr21.tped.gz" | sed 's/^21/chr21/'; } | gzip > "$WORK/sxcoll.tped.gz"

    # A hemizygous fixture: the same genotypes with every heterozygous call in an
    # individual coded male collapsed to a homozygote, which is what a hemizygous
    # call looks like in a TPED.
    gz "$EX/chr21.tfam.gz" | awk '{print NR"\t"$5}' > "$WORK/sxsex.txt"
    gz "$WORK/sxX.tped.gz" | awk 'NR==FNR{sex[$1]=$2; next}{
            printf "%s\t%s\t%s\t%s", $1, $2, $3, $4
            for (i = 5; i <= NF; i += 2) {
                j = (i - 3) / 2; a = $i; b = $(i+1)
                if (sex[j] == 1 && a != b) b = a
                printf "\t%s\t%s", a, b
            }
            printf "\n"
        }' "$WORK/sxsex.txt" - | gzip > "$WORK/sxXhemi.tped.gz"
    { gz "$EX/chr21.tped.gz"; gz "$WORK/sxXhemi.tped.gz"; } | gzip > "$WORK/sxmixhemi.tped.gz"

    sxrun() {   # $1 = out prefix, rest = extra flags; sets $sxst
        p=$1; shift
        # shellcheck disable=SC2086
        "$GARLIC" --tped "$WORK/sxX.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
            --out "$WORK/$p" --force "$@" >/dev/null 2>"$WORK/$p.stderr"
        sxst=$?
    }

    # 1. Detected and undeclared is a hard error, naming the chromosome and
    #    every way out.  A warning here would be a warning attached to an
    #    inflated FROH that the run still produces.
    sxrun sx1
    if [ "$sxst" -eq 1 ] && grep -q "has not been told how to treat: chrX" "$WORK/sx1.stderr"; then ok
    else bad "undeclared chrX did not stop the run"; fi
    for opt in "--sex-system xy" "--autosomes-only" "--sex-system none"; do
        if grep -q -- "$opt" "$WORK/sx1.stderr"; then ok
        else bad "the refusal does not offer $opt"; fi
    done

    # 2. --sex-system none is a true no-op: the same genotypes under a
    #    chromosome named chrX give the same calls as chr21, at the same
    #    positions, differing only in the name.  Byte-identical after
    #    substituting the name back.
    sxrun sx2 --sex-system none
    "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --out "$WORK/sx2ref" --force >/dev/null 2>&1
    if [ -f "$WORK/sx2.roh.bed" ]; then
        sed 's/chrX/chr21/g' "$WORK/sx2.roh.bed" > "$WORK/sx2.renamed.bed"
    fi
    if [ "$sxst" -eq 0 ] && [ -f "$WORK/sx2.renamed.bed" ] && [ -f "$WORK/sx2ref.roh.bed" ] && \
       [ "$(sum "$WORK/sx2.renamed.bed")" = "$(sum "$WORK/sx2ref.roh.bed")" ]; then ok
    else bad "--sex-system none did not reproduce the autosomal run exactly"; fi

    # 3. Roles are dropped, and the log says which and why.  Y/W and the
    #    mitochondrion can carry no run of homozygosity for anybody.
    { gz "$EX/chr21.tped.gz"; gz "$WORK/sxM.tped.gz"; } | gzip > "$WORK/sxmixm.tped.gz"
    "$GARLIC" --tped "$WORK/sxmixm.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system xy --out "$WORK/sx3" --force >/dev/null 2>&1
    if grep -q "Dropping chrM: haploid in every individual" "$WORK/sx3.log"; then ok
    else bad "the mitochondrion was not dropped as haploid"; fi

    # 4. A bare 23 is ambiguous, not sex-linked: PLINK's human code for X, and
    #    an ordinary autosome in any species with 23 or more chromosomes.
    #    Refused without a human --build, resolved with one.
    "$GARLIC" --tped "$WORK/sx23.tped.gz" --tfam "$EX/chr21.tfam.gz" --no-centromere \
        --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --out "$WORK/sx4" --force >/dev/null 2>"$WORK/sx4.stderr"
    if [ $? -eq 1 ] && grep -q "cannot tell what these chromosomes are" "$WORK/sx4.stderr"; then ok
    else bad "a bare chr23 without a human build was not refused"; fi
    # The same file, declared to be an autosome, runs.
    "$GARLIC" --tped "$WORK/sx23.tped.gz" --tfam "$EX/chr21.tfam.gz" --no-centromere \
        --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --sex-system none --out "$WORK/sx4b" --force >/dev/null 2>&1
    if [ -s "$WORK/sx4b.roh.bed" ]; then ok
    else bad "--sex-system none did not accept chr23 as an autosome"; fi
    # With a human build it is PLINK's X: analysed, but as a sex chromosome.
    # The fixture has to be the hemizygous one -- chr21's genotypes relabelled
    # 23 have ordinary heterozygosity in the individuals coded male, and the
    # sex check is right to refuse that (case 9d).
    gz "$WORK/sxXhemi.tped.gz" | sed 's/^chrX/23/' | gzip > "$WORK/sx23hemi.tped.gz"
    "$GARLIC" --tped "$WORK/sx23hemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system xy --out "$WORK/sx4c" --force >/dev/null 2>&1
    if grep -q "^## sex_chromosomes.chr23" "$WORK/sx4c.sexcheck.tsv" 2>/dev/null; then ok
    else bad "chr23 under a human build was not treated as the X"; fi

    # Diploid calls on a chromosome declared hemizygous stop the run too: the
    # alternative is discarding every one of them as impossible, silently.
    "$GARLIC" --tped "$WORK/sx23.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system xy --out "$WORK/sx4d" --force >/dev/null 2>"$WORK/sx4d.stderr"
    if [ $? -eq 1 ] && grep -q "CALLED as diploid there" "$WORK/sx4d.stderr"; then ok
    else bad "diploid genotypes on a hemizygous chromosome were not caught"; fi

    # 5. ZW is the same code path with the other sex heterogametic, so chrZ
    #    must behave exactly as chrX does -- including being refused when the
    #    declared system is the other one.
    "$GARLIC" --tped "$WORK/sxZ.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system xy --out "$WORK/sx5" --force >/dev/null 2>"$WORK/sx5.stderr"
    if [ $? -eq 1 ] && grep -q "has not been told how to treat: chrZ" "$WORK/sx5.stderr"; then ok
    else bad "chrZ under --sex-system xy was not refused"; fi
    "$GARLIC" --tped "$WORK/sxmix.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --autosomes-only --out "$WORK/sx5b" --force >/dev/null 2>&1
    if grep -q "Dropping chrX" "$WORK/sx5b.log"; then ok
    else bad "--autosomes-only did not drop chrX"; fi

    # 6. Matching ignores case and a chr prefix, so every spelling of a name
    #    reaches the same chromosome.  It used to be a prefix-only rule, under
    #    which --chr x matched nothing.
    for spelling in x X chrx chrX CHRX; do
        "$GARLIC" --tped "$WORK/sxmix.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
            --sex-system none --chr "$spelling" --out "$WORK/sx6" --force >/dev/null 2>&1
        if [ -s "$WORK/sx6.roh.bed" ]; then ok
        else bad "--chr $spelling did not match chrX"; fi
    done

    # 7. Two names that differ only by that matching is a collision, and so is
    #    the same name twice -- which is one chromosome whose rows are not
    #    contiguous, silently analysed as two.
    "$GARLIC" --tped "$WORK/sxcoll.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system none --out "$WORK/sx7" --force >/dev/null 2>"$WORK/sx7.stderr"
    if [ $? -eq 1 ] && grep -q "have the same name once case and a" "$WORK/sx7.stderr"; then ok
    else bad "a chromosome-name collision was not refused"; fi

    # 8. The declarations need the system, because which sex CODE is
    #    heterogametic is the part no genotype supplies.
    sxrun sx8 --sex-chr chrX
    if [ "$sxst" -eq 1 ] && grep -q "need --sex-system" "$WORK/sx8.stderr"; then ok
    else bad "--sex-chr without --sex-system was not refused"; fi
    sxrun sx8b --sex-system xy --sex-chr chrQ
    if [ "$sxst" -eq 1 ] && grep -q "is not present in the data" "$WORK/sx8b.stderr"; then ok
    else bad "--sex-chr naming an absent chromosome was not refused"; fi
    sxrun sx8c --sex-system marsupial
    if [ "$sxst" -eq 1 ] && grep -q "must be xy, zw or none" "$WORK/sx8c.stderr"; then ok
    else bad "an unknown --sex-system value was not refused"; fi

    # --- calling on the shared sex chromosome -------------------------------
    # A hemizygous fixture: the same chr21 genotypes relabelled chrX, with
    # every heterozygous call in an individual coded male collapsed to a
    # homozygote, which is what a hemizygous call looks like in a TPED.

    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system xy --out "$WORK/sx9" --force >/dev/null 2>&1
    # 9a. The headline invariant: nobody hemizygous has a call there.  A
    #     heterogametic individual's windows are sums of lod() over genotypes
    #     it does not have, which is exactly 0 and would be called under any
    #     negative cutoff if they were not masked.
    if [ -f "$WORK/sx9.roh.bed" ] && [ -f "$WORK/sx9.sexcheck.tsv" ]; then
        # The zygosity column is found by NAME, not by number: a column added
        # to the sex check should not quietly turn this assertion into one
        # that compares heterozygosity rates to the word "homogametic" and
        # passes for the wrong reason.
        bycls=$(awk -F'\t' '
            FNR == NR && $1 == "ind" { for (i = 1; i <= NF; i++) col[$i] = i; next }
            FNR == NR { if (col["zygosity_used"] > 0) zyg[$1] = $(col["zygosity_used"]); next }
            /^track/ { l = $0; sub(/.*Ind: /, "", l); sub(/ Pop:.*/, "", l); ind = l; next }
            $1 == "chrX" { n[zyg[ind]]++ }
            END { for (k in n) printf "%s=%d ", k, n[k] }
        ' "$WORK/sx9.sexcheck.tsv" "$WORK/sx9.roh.bed")
        case "$bycls" in
            *heterogametic*) bad "a hemizygous individual was called on the shared sex chromosome: $bycls";;
            *homogametic*)   ok;;
            *)               bad "no chrX calls at all in the homogametic individuals";;
        esac
    else bad "the sex-chromosome run produced no output"; fi

    # 9b. Adding the sex chromosome must not move a single autosomal call.
    #     The cutoff and the window size are estimated from the autosomes, so
    #     this holds whether or not they are chosen automatically -- and the
    #     automatic case is the one that would break if the sex chromosome's
    #     windows reached the density.
    "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --out "$WORK/sx9ref" --force >/dev/null 2>&1
    awk '$1 == "chr21" || /^track/' "$WORK/sx9.roh.bed" > "$WORK/sx9.auto.bed"
    if [ "$(sum "$WORK/sx9.auto.bed")" = "$(sum "$WORK/sx9ref.roh.bed")" ]; then ok
    else bad "adding a sex chromosome changed the autosomal calls"; fi

    AUTOBASE="--build hg18 --winsize 60 --error 0.001 --size-bounds 500000 1000000"
    "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" $AUTOBASE \
        --out "$WORK/sx10ref" --force >/dev/null 2>&1
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $AUTOBASE \
        --sex-system xy --out "$WORK/sx10" --force >/dev/null 2>&1
    awk '$1 == "chr21" || /^track/' "$WORK/sx10.roh.bed" > "$WORK/sx10.auto.bed"
    if [ "$(sum "$WORK/sx10.auto.bed")" = "$(sum "$WORK/sx10ref.roh.bed")" ]; then ok
    else bad "the sex chromosome's windows reached the LOD score density"; fi
    # ...and the diagnostic reports what the sex chromosome alone would have
    # given, so reusing the autosomal cutoff is visible rather than implicit.
    if grep -q "Sex chromosome: its own windows would give" "$WORK/sx10.log"; then ok
    else bad "the sex-chromosome cutoff diagnostic was not reported"; fi

    # 9c. The allele frequency is the point of the half-call recode: the
    #     heterogametic sex contributes ONE allele and the homogametic sex two,
    #     computed over everyone, and only then is calling restricted.
    #     Recomputed here from the TPED and the TFAM with no reference to how
    #     garlic does it.
    gz "$WORK/sx9.freq.gz" | awk 'NR > 1 && $1 == "chrX" { print $2"\t"$4"\t"$5 }' > "$WORK/sx9.fx"
    nbad=$(gz "$WORK/sxXhemi.tped.gz" | awk -v sexf="$WORK/sxsex.txt" -v freqf="$WORK/sx9.fx" '
        BEGIN {
            while ((getline l < sexf) > 0)  { split(l, f, "\t"); sex[f[1]] = f[2] }
            while ((getline l < freqf) > 0) { split(l, f, "\t"); want[f[1]] = f[2]; fq[f[1]] = f[3] }
        }
        {
            snp = $2
            if (!(snp in want)) next
            a1 = want[snp]; num = 0; den = 0
            for (i = 5; i <= NF; i += 2) {
                j = (i - 3) / 2; a = $i; b = $(i+1)
                if (sex[j] == 1) { if (a == "0") continue; den += 1; if (a == a1) num += 1 }
                else { if (a == "0" || b == "0") continue; den += 2
                       if (a == a1) num += 1; if (b == a1) num += 1 }
            }
            e = (den > 0 ? num / den : 0)
            d = e - fq[snp]; if (d < 0) d = -d
            if (d > 1e-6) n++
            seen++
        }
        END { if (seen == 0) print "no-loci-compared"; else print n + 0 }
    ')
    if [ "$nbad" = "0" ]; then ok
    else bad "$nbad sex-chromosome allele frequencies do not weight the heterogametic sex as one allele"; fi

    # 9d. The sex check reports, and an inverted --sex-system is caught: every
    #     individual then contradicts its own genotypes, which is the one
    #     failure mode the flag introduces.
    if grep -q "Sex check on the shared sex chromosome" "$WORK/sx9.log" && \
       [ "$(awk 'END{print NR}' "$WORK/sx9.sexcheck.tsv")" -eq 50 ]; then ok
    else bad "the sex check did not write a row per individual"; fi
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system zw --sex-chr chrX --out "$WORK/sx11" --force >/dev/null 2>"$WORK/sx11.stderr"
    if [ $? -eq 1 ] && grep -q "is inverted" "$WORK/sx11.stderr"; then ok
    else bad "an inverted --sex-system was not caught by the sex check"; fi

    # 9e. Sex is optional in a TFAM.  With none recorded, zygosity is inferred
    #     from heterozygosity, and the calls must match the run that was told.
    gz "$EX/chr21.tfam.gz" | awk '{print $1"\t"$2}' > "$WORK/sxnosex.tfam"
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$WORK/sxnosex.tfam" $SEXBASE \
        --sex-system xy --out "$WORK/sx12" --force >/dev/null 2>&1
    if grep -q "inferred from heterozygosity: 45" "$WORK/sx12.log" && \
       [ "$(sum "$WORK/sx12.roh.bed")" = "$(sum "$WORK/sx9.roh.bed")" ]; then ok
    else bad "zygosity inferred from heterozygosity did not reproduce the declared run"; fi

    # 9e2. FROH is reported for the two regions separately, with their own
    #      denominators, and is NA -- not zero -- for an individual that
    #      cannot be autozygous on the sex chromosome.  Zero is a measurement;
    #      this is not one.
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SEXBASE \
        --sex-system xy --froh --out "$WORK/sx14" --force >/dev/null 2>&1
    if grep -q "^## autosome_denominator" "$WORK/sx14.froh.tsv" && \
       grep -q "^## sexchr_denominator" "$WORK/sx14.froh.tsv"; then ok
    else bad "FROH did not report the two denominators separately"; fi
    naz=$(awk -F'\t' '!/^##/ && $1 != "ind" { print $3":"($NF == "NA" ? "NA" : "num") }' \
          "$WORK/sx14.froh.tsv" | sort -u | tr '\n' ';')
    if [ "$naz" = "heterogametic:NA;homogametic:num;" ]; then ok
    else bad "sex-chromosome FROH is not NA for exactly the hemizygous individuals: $naz"; fi
    # One row per individual, not one per size class.
    if [ "$(grep -vc '^##' "$WORK/sx14.froh.tsv")" -eq 46 ]; then ok
    else bad "FROH is not one row per individual plus a header"; fi

    # 10. Pseudoautosomal regions.  There is always a SET of them -- humans
    #     have two -- so the cases that matter are the ones a single-interval
    #     implementation would pass: two regions on one chromosome, given
    #     through both flags, in either order.
    parbase="$SEXBASE --sex-system xy --froh"
    printf 'chrX\t20000000\t21000000\n' > "$WORK/sxpar.txt"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $parbase \
        --par chrX:13560000-14500000 --par-file "$WORK/sxpar.txt" \
        --out "$WORK/sx15" --force >/dev/null 2>&1
    # 10a. Each region reports its OWN dropped-locus count.  A total is
    #      diagnostic enough for one region; with several it is the individual
    #      counts that show a coordinate given in the wrong assembly.
    n1=$(awk '/Excluded region chrX:13560000-14500000 dropped/{print $(NF-1)}' "$WORK/sx15.log")
    n2=$(awk '/Excluded region chrX:20000000-21000000 dropped/{print $(NF-1)}' "$WORK/sx15.log")
    want1=$(gz "$WORK/sxXhemi.tped.gz" | awk '$4>=13560000 && $4<=14500000' | wc -l | tr -d ' ')
    want2=$(gz "$WORK/sxXhemi.tped.gz" | awk '$4>=20000000 && $4<=21000000' | wc -l | tr -d ' ')
    if [ "$n1" = "$want1" ] && [ "$n2" = "$want2" ] && [ "$n1" != "$n2" ]; then ok
    else bad "per-region locus counts wrong: got $n1/$n2, expected $want1/$want2"; fi
    # 10b. No call may overlap either region.
    inpar=$(awk '$1 == "chrX" && (($2 <= 14500000 && $3 >= 13560000) ||
                                  ($2 <= 21000000 && $3 >= 20000000)) { n++ }
                 END { print n + 0 }' "$WORK/sx15.roh.bed")
    if [ "$inpar" = "0" ]; then ok
    else bad "$inpar calls overlap an excluded region"; fi
    # 10c. The order the regions are given in cannot matter -- this is the
    #      regression test against a container that overwrites on repeat.
    printf 'chrX\t13560000\t14500000\n' > "$WORK/sxpar2.txt"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $parbase \
        --par chrX:20000000-21000000 --par-file "$WORK/sxpar2.txt" \
        --out "$WORK/sx16" --force >/dev/null 2>&1
    if [ "$(sum "$WORK/sx16.roh.bed")" = "$(sum "$WORK/sx15.roh.bed")" ] && \
       [ "$(grep -c '^##' "$WORK/sx16.froh.tsv")" -gt 0 ] && \
       [ "$(grep '^## sexchr_denominator' "$WORK/sx16.froh.tsv")" = \
         "$(grep '^## sexchr_denominator' "$WORK/sx15.froh.tsv")" ]; then ok
    else bad "the order the excluded regions are given in changed the result"; fi
    # 10d. An INTERIOR region has to come off the denominator: a terminal one
    #      does so by itself, because dropping its loci moves the first or last
    #      marker inward.  Warned about for the same reason.
    d0=$("$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $parbase \
            --out "$WORK/sx17" --force >/dev/null 2>&1;
         awk -F'\t' '/^## sexchr_denominator/{print $2}' "$WORK/sx17.froh.tsv")
    d1=$("$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $parbase \
            --par chrX:20000000-21000000 --out "$WORK/sx18" --force >/dev/null 2>&1;
         awk -F'\t' '/^## sexchr_denominator/{print $2}' "$WORK/sx18.froh.tsv")
    if [ "$((d0 - d1))" -eq 1000001 ]; then ok
    else bad "an interior excluded region was not subtracted from the denominator: $d0 -> $d1"; fi
    if grep -q "This region is interior" "$WORK/sx18.log"; then ok
    else bad "an interior excluded region was not reported as interior"; fi

    # 10e. Refusals: a region on something that is not a shared sex
    #      chromosome, an inverted one, and one that matches nothing.
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $parbase \
        --par chr21:1-100 --out "$WORK/sx19" --force >/dev/null 2>"$WORK/sx19.stderr"
    if [ $? -eq 1 ] && grep -q "not a shared sex chromosome" "$WORK/sx19.stderr"; then ok
    else bad "an excluded region on an autosome was not refused"; fi
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $parbase \
        --par chrX:500-100 --out "$WORK/sx20" --force >/dev/null 2>"$WORK/sx20.stderr"
    if [ $? -eq 1 ] && grep -q "ends before it starts" "$WORK/sx20.stderr"; then ok
    else bad "an inverted excluded region was not refused"; fi
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $parbase \
        --par chrX:99000000-99100000 --out "$WORK/sx21" --force >/dev/null 2>"$WORK/sx21.stderr"
    if grep -q "contains no loci" "$WORK/sx21.stderr"; then ok
    else bad "an excluded region matching no locus did not warn"; fi

    # 11. A hemizygous VCF.  Writing one allele is how a VCF says hemizygous,
    #     and it used to be rejected outright, which left all of the above
    #     reachable only from TPED-style "A A" coding.
    {
        printf '##fileformat=VCFv4.2\n'
        printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tm1\tm2\tf1\tf2\n'
        printf 'chrX\t1000\ts1\tA\tG\t.\tPASS\t.\tGT\t0\t1\t0/1\t0/0\n'
        printf 'chrX\t2000\ts2\tA\tG\t.\tPASS\t.\tGT\t1\t1\t1/1\t0/1\n'
    } > "$WORK/sxhap.vcf"
    printf 'm1\tP\t1\nm2\tP\t1\nf1\tP\t2\nf2\tP\t2\n' > "$WORK/sxhap.pop"
    # Undeclared, it is still an error: a haploid genotype on an autosome is
    # malformed input and that check is worth keeping.
    "$GARLIC" --vcf "$WORK/sxhap.vcf" --pop "$WORK/sxhap.pop" --no-centromere --error 0.001 \
        --winsize 2 --lod-cutoff 2.5 --size-bounds 100 200 \
        --out "$WORK/sx22" --force >/dev/null 2>"$WORK/sx22.stderr"
    if [ $? -ne 0 ] && grep -q "has ploidy 1" "$WORK/sx22.stderr"; then ok
    else bad "a haploid genotype was accepted without a declaration"; fi
    # The hint that follows it is three lines, and the `if` guarding them was
    # unbraced: only the first line was conditional, so the other two printed
    # on ANY chromosome.  Both halves are asserted -- the whole hint where it
    # applies, and none of it where it does not.  On the chr7 fixture below the
    # pre-fix binary emitted
    #     ERROR: sample m1 at chr7:2000 has ploidy 3; garlic calls ROH from
    #     diploid genotypes only.
    #         --sex-system makes a haploid genotype there a hemizygous call rather
    #         than an error.
    # -- the two orphaned lines, without the sentence that introduces them.
    if grep -q "conventionally a sex chromosome" "$WORK/sx22.stderr" &&
       grep -q "sex-system makes a haploid genotype" "$WORK/sx22.stderr"; then ok
    else bad "the ploidy refusal on chrX lost the sex-chromosome hint"; fi
    {
        printf '##fileformat=VCFv4.2\n'
        printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tm1\tm2\tf1\tf2\n'
        printf 'chr7\t1000\ts1\tA\tG\t.\tPASS\t.\tGT\t0/1\t1/1\t0/1\t0/0\n'
        printf 'chr7\t2000\ts2\tA\tG\t.\tPASS\t.\tGT\t0/1/1\t1/1\t1/1\t0/1\n'
    } > "$WORK/auto3n.vcf"
    "$GARLIC" --vcf "$WORK/auto3n.vcf" --pop "$WORK/sxhap.pop" --no-centromere --error 0.001 \
        --winsize 2 --lod-cutoff 2.5 --size-bounds 100 200 \
        --out "$WORK/auto3n" --force >/dev/null 2>"$WORK/auto3n.stderr"
    if [ $? -ne 0 ] && grep -q "has ploidy 3" "$WORK/auto3n.stderr" &&
       ! grep -q "sex-system" "$WORK/auto3n.stderr"; then ok
    else bad "a non-diploid genotype on an autosome was advised to use --sex-system"; fi
    # Declared, it is a hemizygous call: a half call, which contributes its one
    # allele to the frequency and no genotype.
    "$GARLIC" --vcf "$WORK/sxhap.vcf" --pop "$WORK/sxhap.pop" --no-centromere --error 0.001 \
        --winsize 2 --lod-cutoff 2.5 --size-bounds 100 200 --sex-system xy \
        --out "$WORK/sx23run" --force >/dev/null 2>"$WORK/sx23run.stderr"
    if [ $? -eq 0 ] && [ -f "$WORK/sx23run.sexcheck.tsv" ]; then ok
    else bad "a declared hemizygous VCF was not read"; fi
    # The haploid calls are what establishes zygosity here: those individuals
    # have no diploid genotype at all, so the heterozygosity rate cannot.
    hap=$(awk -F'\t' '$1 == "ind" { for (i = 1; i <= NF; i++) c[$i] = i; next }
                       !/^##/ { printf "%s:%s:%s ", $1, $(c["n_half"]), $(c["zygosity_used"]) }' \
          "$WORK/sx23run.sexcheck.tsv")
    if [ "$hap" = "m1:2:heterogametic m2:2:heterogametic f1:0:homogametic f2:0:homogametic " ]; then ok
    else bad "haploid calls did not establish zygosity: $hap"; fi

    # 12. --freq-only streams the file and never builds the chromosome table,
    #     so it has to answer the same questions the full path does.  It used
    #     to count every individual as diploid and write a frequency file that
    #     --freq-file would then feed back into a run.
    "$GARLIC" --tped "$WORK/sxXhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" --no-centromere \
        --error 0.001 --sex-system xy --freq-only --out "$WORK/sx24" >/dev/null 2>&1
    "$GARLIC" --tped "$WORK/sxXhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" --no-centromere \
        --error 0.001 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --sex-system xy --out "$WORK/sx25" --force >/dev/null 2>&1
    if [ "$(sumgz "$WORK/sx24.freq.gz")" = "$(sumgz "$WORK/sx25.freq.gz")" ]; then ok
    else bad "--freq-only and the full path disagree on the sex chromosome frequency"; fi
    # Undeclared, it refuses rather than counting everyone as diploid.
    "$GARLIC" --tped "$WORK/sxXhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" --no-centromere \
        --error 0.001 --freq-only --out "$WORK/sx26" >/dev/null 2>"$WORK/sx26.stderr"
    if [ $? -ne 0 ] && grep -q "has not been told how to treat" "$WORK/sx26.stderr"; then ok
    else bad "--freq-only did not refuse an undeclared sex chromosome"; fi
    # Sex it cannot infer in one pass: refuse, and say where it would be
    # inferred instead.
    "$GARLIC" --tped "$WORK/sxXhemi.tped.gz" --tfam "$WORK/sxnosex.tfam" --no-centromere \
        --error 0.001 --sex-system xy --freq-only --out "$WORK/sx27" >/dev/null 2>"$WORK/sx27.stderr"
    if [ $? -ne 0 ] && grep -q "cannot infer it from" "$WORK/sx27.stderr"; then ok
    else bad "--freq-only did not refuse an unrecorded sex"; fi
    # An autosome-only run is untouched by any of this.
    "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --no-centromere \
        --error 0.001 --freq-only --out "$WORK/sx28" >/dev/null 2>&1
    if [ $? -eq 0 ] && [ -s "$WORK/sx28.freq.gz" ]; then ok
    else bad "--freq-only broke on autosomes"; fi
    # A malformed record used to abort: "terminating due to uncaught exception
    # of type int", exit 134, with no diagnosis.
    printf '##fileformat=VCFv4.2\n#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\ts1\nchr1\t1\tr\tA\tG\t.\tPASS\t.\tGT\t0\n' > "$WORK/sxbad.vcf"
    expect_exit 2 "--freq-only reports a bad record instead of aborting" \
        "$GARLIC" --vcf "$WORK/sxbad.vcf" --no-centromere --error 0.001 --freq-only \
        --out "$WORK/sx29"

    # 13. --build supplies the human X regions on its own.  The fixture puts
    #     chr21's markers inside hg19's PAR1 so the table has something to bite
    #     on; PAR2 is then empty, which is a fact about the data rather than a
    #     wrong coordinate and must not warn.
    gz "$WORK/sxXhemi.tped.gz" | awk 'BEGIN{OFS="\t"} {$4 = $4 - 13000000 + 100000; print}' \
        | gzip > "$WORK/sxpar19.tped.gz"
    PARBASE="--error 0.001 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 --sex-system xy"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxpar19.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg19 $PARBASE \
        --out "$WORK/sx30" --force >/dev/null 2>"$WORK/sx30.stderr"
    want=$(gz "$WORK/sxpar19.tped.gz" | awk '$4>=60001 && $4<=2699520' | wc -l | tr -d ' ')
    got=$(awk '/Excluded region chrX:60001-2699520 dropped/{print $(NF-1)}' "$WORK/sx30.log")
    if [ "$got" = "$want" ] && [ "$want" != "0" ]; then ok
    else bad "the hg19 PAR1 table dropped $got loci, expected $want"; fi
    if grep -q "Pseudoautosomal regions for hg19" "$WORK/sx30.log"; then ok
    else bad "the built-in PAR table was not reported"; fi
    if grep -q "contains no loci" "$WORK/sx30.stderr"; then
        bad "an empty region from the build table warned as if it were a wrong coordinate"
    else ok; fi
    # The coordinates are the assembly's, so a different build must move them.
    "$GARLIC" --tped "$WORK/sxpar19.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg38 $PARBASE \
        --out "$WORK/sx31" --force >/dev/null 2>&1
    if grep -q "Excluded region chrX:10001-2781479" "$WORK/sx31.log" && \
       ! grep -q "Excluded region chrX:60001-2699520" "$WORK/sx31.log"; then ok
    else bad "the PAR table does not follow --build"; fi
    # Named regions replace the table; --par none keeps them all.
    "$GARLIC" --tped "$WORK/sxpar19.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg19 $PARBASE \
        --par chrX:200000-300000 --out "$WORK/sx32" --force >/dev/null 2>&1
    if grep -q "Excluded region chrX:200000-300000" "$WORK/sx32.log" && \
       ! grep -q "Excluded region chrX:60001-2699520" "$WORK/sx32.log"; then ok
    else bad "a named region did not replace the build's table"; fi
    "$GARLIC" --tped "$WORK/sxpar19.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg19 $PARBASE \
        --par none --out "$WORK/sx33" --force >/dev/null 2>&1
    if ! grep -q "Excluded region" "$WORK/sx33.log"; then ok
    else bad "--par none did not suppress the build's table"; fi
    # Under PLINK's numbering the same chromosome is called 23, and a region
    # filed under "chrX" would not be found on it.
    "$GARLIC" --tped "$WORK/sx23hemi.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 $PARBASE \
        --out "$WORK/sx34" --force >/dev/null 2>"$WORK/sx34.stderr"
    if [ $? -eq 0 ] && grep -q "applied to chr23" "$WORK/sx34.log"; then ok
    else bad "the build's PAR table was not filed under the name the data uses"; fi

    # 9f. A cutoff at or below the uncallable-window sentinel would call every
    #     window that exists to be uncallable, including these.
    expect_exit 1 "--lod-cutoff below the MISSING sentinel" \
        "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --build hg18 \
        --winsize 60 --error 0.001 --lod-cutoff -9999 --size-bounds 500000 1000000 \
        --out "$WORK/sx13" --force

    # 14. --sexchr-lod-cutoff and --sexchr-winsize: the escape hatch for a
    #     cohort where the autosomal estimates do not suit the sex chromosome.
    #     The fixture is the mixed one, so every case can check that what
    #     changed on the sex chromosome left the autosomes alone.
    SXEST="--build hg18 --error 0.001 --size-bounds 500000 1000000 --sex-system xy"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SXEST \
        --winsize 60 --lod-cutoff 2.5 --out "$WORK/sx40" --force >/dev/null 2>&1
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SXEST \
        --winsize 60 --lod-cutoff 2.5 --sexchr-lod-cutoff 1.5 --sexchr-winsize 30 \
        --out "$WORK/sx41" --force >/dev/null 2>&1
    # A different window size and cutoff on that chromosome has to change what
    # is called there -- otherwise the flags are being read and discarded.
    n40=$(awk '$1 == "chrX"' "$WORK/sx40.roh.bed" | wc -l | tr -d ' ')
    n41=$(awk '$1 == "chrX"' "$WORK/sx41.roh.bed" | wc -l | tr -d ' ')
    if [ "$n40" -gt 0 ] && [ "$n41" -ne "$n40" ]; then ok
    else bad "--sexchr-winsize/--sexchr-lod-cutoff changed nothing on the sex chromosome ($n40 vs $n41)"; fi
    # and nothing anywhere else.
    awk '$1 != "chrX"' "$WORK/sx40.roh.bed" > "$WORK/sx40.auto.bed"
    awk '$1 != "chrX"' "$WORK/sx41.roh.bed" > "$WORK/sx41.auto.bed"
    if diff "$WORK/sx40.auto.bed" "$WORK/sx41.auto.bed" >/dev/null; then ok
    else bad "the sex chromosome's own window size and cutoff moved autosomal calls"; fi
    # The run record has to say what was applied where.  Both numbers, from
    # the run rather than from the command line: this is the file --load-params
    # reads and the one a reader checks a published cutoff against.
    if grep -q '"sexchr_winsize": 30' "$WORK/sx41.params.json" &&
       grep -q '"sexchr_lod_cutoff": 1.5' "$WORK/sx41.params.json"; then ok
    else bad "the parameter record does not carry the sex chromosome's window size and cutoff"; fi
    # Without the flags they are still recorded, holding the autosomal values:
    # a reader should not have to know which flags were set to learn what the
    # sex chromosome was called at.
    if grep -q '"sexchr_winsize": 60' "$WORK/sx40.params.json" &&
       grep -q '"sexchr_lod_cutoff": 2.5' "$WORK/sx40.params.json"; then ok
    else bad "the parameter record omits the sex chromosome's resolved values by default"; fi
    # And not at all when no sex chromosome was analysed, where they would be
    # the autosomal numbers under another name.
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SXEST \
        --winsize 60 --lod-cutoff 2.5 --autosomes-only --out "$WORK/sx42" --force >/dev/null 2>&1
    if ! grep -q 'sexchr_winsize' "$WORK/sx42.params.json"; then ok
    else bad "an autosome-only run recorded a sex chromosome window size"; fi
    # The log says it too, next to the autosomal window size, because a reader
    # who sees one number will assume it applied to the whole run.
    if grep -q "Window size on the shared sex chromosome: 30" "$WORK/sx41.log" &&
       grep -q "cutoff on the shared sex chromosome: 1.5" "$WORK/sx41.log"; then ok
    else bad "the log does not report the sex chromosome's window size and cutoff"; fi
    # --load-params replays them: the record is only worth writing if it is
    # enough to reproduce the run.
    "$GARLIC" --load-params "$WORK/sx41.params.json" --out "$WORK/sx43" --force >/dev/null 2>&1
    if diff "$WORK/sx41.roh.bed" "$WORK/sx43.roh.bed" >/dev/null; then ok
    else bad "a run with sex-chromosome estimates did not replay from its parameter record"; fi
    # A window size without a cutoff to go with it is refused: LOD scores move
    # with the number of SNPs in a window, so the autosomal cutoff would be
    # applied to numbers it does not describe.
    # shellcheck disable=SC2086
    expect_exit 1 "--sexchr-winsize without --sexchr-lod-cutoff" \
        "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SXEST \
        --winsize 60 --lod-cutoff 2.5 --sexchr-winsize 30 --out "$WORK/sx44" --force
    # Given with nothing to apply them to, rather than silently ignored.
    # shellcheck disable=SC2086
    expect_exit 1 "--sexchr-lod-cutoff with no shared sex chromosome" \
        "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SXEST \
        --winsize 60 --lod-cutoff 2.5 --sexchr-lod-cutoff 1.5 --autosomes-only \
        --out "$WORK/sx45" --force
    # The same sentinel check the autosomal cutoff gets.
    # shellcheck disable=SC2086
    expect_exit 1 "--sexchr-lod-cutoff below the MISSING sentinel" \
        "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SXEST \
        --winsize 60 --lod-cutoff 2.5 --sexchr-lod-cutoff -9999 --out "$WORK/sx46" --force
    # Each row of a window-size exploration would need its own sex-chromosome
    # cutoff for one to mean anything, and --freq-only calls no ROH at all.
    # shellcheck disable=SC2086
    expect_exit 1 "--sexchr-lod-cutoff with --winsize-multi" \
        "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" $SXEST \
        --winsize-multi 40 60 --sexchr-lod-cutoff 1.5 --out "$WORK/sx47" --force
    expect_exit 1 "--sexchr-winsize with --freq-only" \
        "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" \
        --sex-system xy --freq-only --sexchr-winsize 30 --sexchr-lod-cutoff 1.5 \
        --out "$WORK/sx48" --force

    # 15. --weighted.  Both LD statistics skip a genotype that is not called,
    #     and a half call is not called, so the LD matrix on the shared sex
    #     chromosome is estimated among the individuals who are diploid there.
    #     The map is chr21's, duplicated under the other name.
    { gz "$EX/chr21.map.gz"; gz "$EX/chr21.map.gz" | sed 's/^21/chrX/'; } | gzip > "$WORK/sxmix.map.gz"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" --map "$WORK/sxmix.map.gz" \
        --weighted $SXEST --winsize 60 --lod-cutoff 2.5 --out "$WORK/sx50" --force >/dev/null 2>&1
    awk -F'\t' '$1 == "chrX" { print $4 }' "$WORK/sx50.roh.bed" | sort -u > "$WORK/sx50.called"
    gz "$EX/chr21.tfam.gz" | awk '$5 == 1 { print $2 }' | sort -u > "$WORK/sx50.hetero"
    nbad=$(comm -12 "$WORK/sx50.called" "$WORK/sx50.hetero" | wc -l | tr -d ' ')
    ncalled=$(wc -l < "$WORK/sx50.called" | tr -d ' ')
    if [ "$ncalled" -gt 0 ] && [ "$nbad" -eq 0 ]; then ok
    else bad "--weighted called $nbad heterogametic individuals on the sex chromosome"; fi
    # The weighted path must leave the autosomes alone too.
    "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --map "$EX/chr21.map.gz" \
        --weighted --build hg18 --winsize 60 --error 0.001 --lod-cutoff 2.5 \
        --size-bounds 500000 1000000 --out "$WORK/sx51" --force >/dev/null 2>&1
    awk '$1 != "chrX"' "$WORK/sx50.roh.bed" | sed 's/^chr21/21/' > "$WORK/sx50.auto"
    sed 's/^chr21/21/' "$WORK/sx51.roh.bed" > "$WORK/sx51.auto"
    if diff "$WORK/sx51.auto" "$WORK/sx50.auto" >/dev/null; then ok
    else bad "--weighted moved an autosomal call when a sex chromosome was present"; fi
    # A subsample smaller than the heterogametic count: drawn from the whole
    # cohort it would spend most of its budget on individuals with no
    # genotypes there, and could contain none who has any.  (The NaN that
    # produced is covered by the unit tests, which reach hr2 and r2 directly;
    # this checks the chromosome is still informed at all.)
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/sxmixhemi.tped.gz" --tfam "$EX/chr21.tfam.gz" --map "$WORK/sxmix.map.gz" \
        --weighted $SXEST --winsize 60 --lod-cutoff 2.5 --ld-subsample 4 --seed 1 \
        --out "$WORK/sx52" --force >/dev/null 2>&1
    if [ "$(awk '$1 == "chrX"' "$WORK/sx52.roh.bed" | wc -l | tr -d ' ')" -gt 0 ]; then ok
    else bad "--weighted with a small LD subsample called nothing on the sex chromosome"; fi

    # 16. --tgls.  A half call carries no genotype, so lod() takes its default
    #     branch and never reads the error rate; the likelihoods still have to
    #     line up with the sites after the sex chromosome is handled.  The
    #     fixture is example.tped/example.tgls -- the tracked pair with usable
    #     GL values -- with chromosome 22 relabelled and made hemizygous.
    awk '{ print NR"\t"$5 }' "$EX/example.tfam" > "$WORK/sxex.sex"
    gz "$EX/example.tped.gz" | awk -v OFS='\t' 'NR == FNR { sex[$1] = $2; next }
        $1 != 22 { print; next }
        { $1 = "chrX"
          for (i = 5; i <= NF; i += 2) { j = (i-3)/2; if (sex[j] == 1 && $i != $(i+1)) $(i+1) = $i }
          print }' "$WORK/sxex.sex" - | gzip > "$WORK/sxex.tped.gz"
    gz "$EX/example.tgls.gz" | sed 's/^22\t/chrX\t/' | gzip > "$WORK/sxex.tgls.gz"
    "$GARLIC" --tped "$WORK/sxex.tped.gz" --tfam "$EX/example.tfam" --tgls "$WORK/sxex.tgls.gz" \
        --gl-type GL --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --sex-system xy --out "$WORK/sx53" --force >/dev/null 2>&1
    awk -F'\t' '$1 == "chrX" { print $4 }' "$WORK/sx53.roh.bed" | sort -u > "$WORK/sx53.called"
    awk '$5 == 1 { print $2 }' "$EX/example.tfam" | sort -u > "$WORK/sx53.hetero"
    nbad=$(comm -12 "$WORK/sx53.called" "$WORK/sx53.hetero" | wc -l | tr -d ' ')
    if [ "$(wc -l < "$WORK/sx53.called" | tr -d ' ')" -gt 0 ] && [ "$nbad" -eq 0 ]; then ok
    else bad "--tgls called $nbad heterogametic individuals on the sex chromosome"; fi
    # The allele frequencies do not depend on the likelihoods at all, so the
    # --tgls run and the --error run have to agree on them exactly.
    "$GARLIC" --tped "$WORK/sxex.tped.gz" --tfam "$EX/example.tfam" --error 0.001 \
        --build hg18 --winsize 60 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --sex-system xy --out "$WORK/sx54" --force >/dev/null 2>&1
    gz "$WORK/sx53.freq.gz" | awk '$1 == "chrX"' > "$WORK/sx53.xfreq"
    gz "$WORK/sx54.freq.gz" | awk '$1 == "chrX"' > "$WORK/sx54.xfreq"
    if [ -s "$WORK/sx53.xfreq" ] && diff "$WORK/sx53.xfreq" "$WORK/sx54.xfreq" >/dev/null; then ok
    else bad "--tgls and --error disagree on the sex chromosome's allele frequencies"; fi

    # 17. Haploid calls in a VCF alongside GQ, PL and GL.  A haploid PL array
    #     has one value per ALLELE -- two at a biallelic site, not the three
    #     the diploid parser requires.  It is never parsed, because a half
    #     call is not a called genotype and takes the earlier branch, and
    #     these three cases are what keeps that ordering.
    {
        printf '##fileformat=VCFv4.2\n'
        printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tm1\tm2\tf1\tf2\n'
        printf 'chrX\t1000\ts1\tA\tG\t.\tPASS\t.\tGT:GQ:PL:GL\t0:40:0,60:0,-6\t1:40:60,0:-6,0\t0/1:40:60,0,60:-6,0,-6\t0/0:40:0,60,120:0,-6,-12\n'
        printf 'chrX\t2000\ts2\tA\tG\t.\tPASS\t.\tGT:GQ:PL:GL\t1:40:60,0:-6,0\t1:40:60,0:-6,0\t1/1:40:120,60,0:-12,-6,0\t0/1:40:60,0,60:-6,0,-6\n'
    } > "$WORK/sxhapgl.vcf"
    for t in GQ PL GL; do
        "$GARLIC" --vcf "$WORK/sxhapgl.vcf" --pop "$WORK/sxhap.pop" --no-centromere \
            --winsize 2 --lod-cutoff 2.5 --size-bounds 100 200 --sex-system xy \
            --gl-type "$t" --out "$WORK/sxgl$t" --force >/dev/null 2>&1
        if [ $? -eq 0 ] && [ -f "$WORK/sxgl$t.sexcheck.tsv" ]; then ok
        else bad "a hemizygous VCF was not read with --gl-type $t"; fi
    done
}

# ---------------------------------------------------------------------------
# --froh-denominator.  Two conventions that differ by several percent: the
# span the markers cover (what garlic has always divided by) and the full
# length of each analysed chromosome (what published FROH use).  The whole
# point is a number reproducible from an external table, so every check here
# compares against the table rather than against a recorded value.
# ---------------------------------------------------------------------------
froh_denominator() {
    echo "== FROH denominator =="
    FDBASE="--tfam $EX/example.tfam --winsize 60 --error 0.001 --lod-cutoff 2.5"
    FDBASE="$FDBASE --size-bounds 500000 1000000 --froh --force"

    # The bundled example is hg18 -- established by the only build under which
    # no marker lies past the end of its chromosome, which case 6 checks.
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --build hg18 \
        --out "$WORK/fd1" >/dev/null 2>&1
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --build hg18 \
        --froh-denominator assembly --out "$WORK/fd2" >/dev/null 2>&1

    # 1. The denominator IS the sum of the table's autosome rows.  Summed here
    #    from centromeres/chr_lengths.txt rather than pasted in, so the file
    #    and the compiled-in table cannot drift apart unnoticed.
    want=$(awk -F'\t' '$1 == "hg18" && $2 != "chrX" && $2 != "chrY" { s += $3 } END { printf "%d", s }' \
           "$ROOT/centromeres/chr_lengths.txt")
    got=$(awk -F'\t' '$1 == "## autosome_denominator" { print $2 }' "$WORK/fd2.froh.tsv")
    if [ "$got" = "$want" ]; then ok
    else bad "assembly denominator is $got, the hg18 autosomes sum to $want"; fi

    # 2. Nothing is subtracted, where analyzed subtracts the centromere and
    #    stops at the outermost marker.  Both differences point the same way,
    #    so assembly has to be the larger number -- and case 1 has already
    #    pinned it to the table.  (PARs are the other thing not subtracted;
    #    that needs a sex chromosome and is case 11.)
    gotan=$(awk -F'\t' '$1 == "## autosome_denominator" { print $2 }' "$WORK/fd1.froh.tsv")
    if [ -n "$gotan" ] && [ "$gotan" -lt "$want" ]; then ok
    else bad "the analyzed denominator ($gotan) is not smaller than the assembly one ($want)"; fi

    # 3. The autozygous LENGTHS are identical between modes -- only the
    #    division changes.  A denominator flag that moved a call would be a
    #    different bug entirely.
    awk -F'\t' 'NR == FNR { if (!/^##/) a[$1] = $0; next }
                !/^##/ && $1 in a { n++ }
                END { print n }' "$WORK/fd1.froh.tsv" "$WORK/fd2.froh.tsv" > /dev/null
    cut -f1-3 < "$WORK/fd1.froh.tsv" | grep -v '^##' > "$WORK/fd1.ids"
    cut -f1-3 < "$WORK/fd2.froh.tsv" | grep -v '^##' > "$WORK/fd2.ids"
    grep -v '^##' "$WORK/fd1.froh.tsv" | awk -F'\t' 'NR==1{for(i=1;i<=NF;i++)c[$i]=i;next}{print $1"\t"$(c["auto_ALL_len"])}' > "$WORK/fd1.len"
    grep -v '^##' "$WORK/fd2.froh.tsv" | awk -F'\t' 'NR==1{for(i=1;i<=NF;i++)c[$i]=i;next}{print $1"\t"$(c["auto_ALL_len"])}' > "$WORK/fd2.len"
    if diff "$WORK/fd1.ids" "$WORK/fd2.ids" >/dev/null && diff "$WORK/fd1.len" "$WORK/fd2.len" >/dev/null; then ok
    else bad "--froh-denominator changed the autozygous totals, not just the denominator"; fi

    # 4. And FROH is the total over that denominator, to the printed digits.
    bad4=$(grep -v '^##' "$WORK/fd2.froh.tsv" |
        awk -F'\t' -v d="$want" 'NR==1{for(i=1;i<=NF;i++)c[$i]=i;next}
            { e = $(c["auto_ALL_len"]) / d
              if ((e - $(c["auto_ALL_froh"]))^2 > 1e-14) n++ } END { print n+0 }')
    if [ "$bad4" -eq 0 ]; then ok
    else bad "$bad4 individuals' FROH are not their total over the assembly denominator"; fi

    # 5. --chr restricts the denominator to that chromosome.  Summing the whole
    #    assembly for a one-chromosome run would put FROH near zero.
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --build hg18 --chr 21 \
        --froh-denominator assembly --out "$WORK/fd4" >/dev/null 2>&1
    want21=$(awk -F'\t' '$1 == "hg18" && $2 == "chr21" { print $3 }' "$ROOT/centromeres/chr_lengths.txt")
    got21=$(awk -F'\t' '$1 == "## autosome_denominator" { print $2 }' "$WORK/fd4.froh.tsv")
    if [ "$got21" = "$want21" ]; then ok
    else bad "--chr 21 gave a denominator of $got21, chr21 is $want21"; fi

    # 6. A marker past the end of its chromosome means the coordinates and the
    #    lengths are different assemblies.  Under assembly that makes the
    #    denominator wrong, so the run stops; under analyzed the lengths feed
    #    nothing, so it warns -- and it still matters, because the centromere
    #    positions in use came from the same wrong build.
    # shellcheck disable=SC2086
    expect_exit 1 "a wrong --build under assembly" \
        "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --build hg38 \
        --froh-denominator assembly --out "$WORK/fd5"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --build hg38 \
        --out "$WORK/fd6" >/dev/null 2>"$WORK/fd6.stderr"
    if [ $? -eq 0 ] && grep -q "markers lie past the end" "$WORK/fd6.stderr"; then ok
    else bad "a wrong --build under analyzed did not warn"; fi
    # The right build says nothing.
    if ! grep -q "markers lie past the end" "$WORK/fd1.log"; then ok
    else bad "the correct build reported markers past the end of a chromosome"; fi

    # 7. --chr-lengths: the two-column form, a samtools .fai unchanged, and
    #    precedence over --build.
    awk -F'\t' '$1 == "hg18" && $2 != "chrX" && $2 != "chrY" { print $2"\t"$3 }' \
        "$ROOT/centromeres/chr_lengths.txt" > "$WORK/fd.lens"
    awk -v OFS='\t' '{ print $1, $2, 0, 60, 61 }' "$WORK/fd.lens" > "$WORK/fd.fa.fai"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --no-centromere \
        --chr-lengths "$WORK/fd.lens" --froh-denominator assembly --out "$WORK/fd7" >/dev/null 2>&1
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --no-centromere \
        --chr-lengths "$WORK/fd.fa.fai" --froh-denominator assembly --out "$WORK/fd8" >/dev/null 2>&1
    grep -v chromosome_lengths "$WORK/fd7.froh.tsv" > "$WORK/fd7.cmp"
    grep -v chromosome_lengths "$WORK/fd8.froh.tsv" > "$WORK/fd8.cmp"
    got7=$(awk -F'\t' '$1 == "## autosome_denominator" { print $2 }' "$WORK/fd7.froh.tsv")
    got8=$(awk -F'\t' '$1 == "## autosome_denominator" { print $2 }' "$WORK/fd8.froh.tsv")
    if [ "$got7" = "$want" ] && [ "$got8" = "$want" ] &&
       diff "$WORK/fd7.cmp" "$WORK/fd8.cmp" >/dev/null; then ok
    else bad "two-column gave $got7 and .fai gave $got8, expected $want for both"; fi
    # Doubling every length in the file doubles the denominator even though
    # --build is also given, which is the precedence rule.
    awk -v OFS='\t' '{ print $1, $2 * 2 }' "$WORK/fd.lens" > "$WORK/fd.dbl"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --build hg18 \
        --chr-lengths "$WORK/fd.dbl" --froh-denominator assembly --out "$WORK/fd9" >/dev/null 2>&1
    got9=$(awk -F'\t' '$1 == "## autosome_denominator" { print $2 }' "$WORK/fd9.froh.tsv")
    want2=$(awk -F'\t' '{ s += $2 } END { printf "%d", s }' "$WORK/fd.dbl")
    if [ "$got9" = "$want2" ]; then ok
    else bad "--chr-lengths did not take precedence over --build ($got9, expected $want2)"; fi

    # 8. A chromosome with no length stops the run.  Falling back to its marker
    #    span would make the denominator neither convention, and the warning
    #    would not survive into a figure.
    grep -v "^chr9	" "$WORK/fd.lens" > "$WORK/fd.gap"
    # shellcheck disable=SC2086
    expect_exit 1 "a chromosome missing from --chr-lengths" \
        "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --no-centromere \
        --chr-lengths "$WORK/fd.gap" --froh-denominator assembly --out "$WORK/fd10"
    # shellcheck disable=SC2086
    expect_exit 1 "assembly with no lengths available at all" \
        "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --no-centromere \
        --froh-denominator assembly --out "$WORK/fd11"

    # 9. Combinations that cannot be honoured.
    # shellcheck disable=SC2086
    expect_exit 1 "assembly with --cm" \
        "$GARLIC" --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --map "$EX/chr21.map.gz" \
        --cm --build hg18 --winsize 60 --error 0.001 --lod-cutoff 0.5 --size-bounds 1 2 \
        --froh --froh-denominator assembly --out "$WORK/fd12" --force
    # shellcheck disable=SC2086
    expect_exit 1 "--chr-lengths without assembly" \
        "$GARLIC" --tped "$EX/example.tped.gz" $FDBASE --build hg18 \
        --chr-lengths "$WORK/fd.lens" --out "$WORK/fd13"
    expect_exit 1 "assembly without --froh" \
        "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 \
        --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
        --froh-denominator assembly --out "$WORK/fd14" --force
    expect_exit 1 "an unknown --froh-denominator" \
        "$GARLIC" --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 \
        --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 --froh \
        --froh-denominator genome --out "$WORK/fd15" --force

    # 10. A VCF states its own lengths.  The decoys, the alt contig and chrEBV
    #     are in the header and must never be consulted -- they carry no data,
    #     so nothing looks them up, which is what makes this need no list of
    #     "real" chromosome names.
    {
        printf '##fileformat=VCFv4.2\n'
        printf '##contig=<ID=chr21,length=48129895>\n'
        printf '##contig=<ID=chrUn_KI270302v1,length=2274>\n'
        printf '##contig=<ID=chr21_KI270872v1_alt,length=82692>\n'
        printf '##contig=<ID=chrEBV,length=171823>\n'
        printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\ts1\ts2\ts3\ts4\n'
        for p in 1000 200000 400000 600000 800000 1000000; do
            printf 'chr21\t%s\tv%s\tA\tG\t.\tPASS\t.\tGT\t0/0\t0/0\t0/1\t0/0\n' "$p" "$p"
        done
    } > "$WORK/fdh.vcf"
    printf 's1\tP\ns2\tP\ns3\tP\ns4\tP\n' > "$WORK/fdh.pop"
    "$GARLIC" --vcf "$WORK/fdh.vcf" --pop "$WORK/fdh.pop" --no-centromere --winsize 2 \
        --error 0.001 --lod-cutoff 2.5 --size-bounds 100 200 --froh \
        --froh-denominator assembly --out "$WORK/fd16" --force >/dev/null 2>&1
    got16=$(awk -F'\t' '$1 == "## autosome_denominator" { print $2 }' "$WORK/fd16.froh.tsv")
    if [ "$got16" = "48129895" ]; then ok
    else bad "the VCF header gave a denominator of $got16, its chr21 contig is 48129895"; fi
    # Its length disagrees with hg38, and one of them is wrong.  This is the
    # only witness garlic has to a --build that does not match the data.
    expect_exit 1 "a VCF header that contradicts --build" \
        "$GARLIC" --vcf "$WORK/fdh.vcf" --pop "$WORK/fdh.pop" --build hg38 --winsize 2 \
        --error 0.001 --lod-cutoff 2.5 --size-bounds 100 200 --froh --out "$WORK/fd17" --force

    # 11. The shared sex chromosome gets its chromosome's raw length, PARs
    #     included -- the inconsistency the raw definition accepts, and the one
    #     the published denominators have.
    awk '{ print NR"\t"$5 }' "$EX/example.tfam" > "$WORK/fdsex.txt"
    gz "$EX/example.tped.gz" | awk -v OFS='\t' 'NR == FNR { sex[$1] = $2; next }
        $1 != 22 { print; next }
        { $1 = "chrX"
          for (i = 5; i <= NF; i += 2) { j = (i-3)/2; if (sex[j] == 1 && $i != $(i+1)) $(i+1) = $i }
          print }' "$WORK/fdsex.txt" - | gzip > "$WORK/fdsex.tped.gz"
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/fdsex.tped.gz" $FDBASE --build hg18 --sex-system xy \
        --froh-denominator assembly --out "$WORK/fd18" >/dev/null 2>&1
    # shellcheck disable=SC2086
    "$GARLIC" --tped "$WORK/fdsex.tped.gz" $FDBASE --build hg18 --sex-system xy --par none \
        --froh-denominator assembly --out "$WORK/fd19" >/dev/null 2>&1
    wantx=$(awk -F'\t' '$1 == "hg18" && $2 == "chrX" { print $3 }' "$ROOT/centromeres/chr_lengths.txt")
    gotx=$(awk -F'\t' '$1 == "## sexchr_denominator" { print $2 }' "$WORK/fd18.froh.tsv")
    gotxn=$(awk -F'\t' '$1 == "## sexchr_denominator" { print $2 }' "$WORK/fd19.froh.tsv")
    if [ "$gotx" = "$wantx" ] && [ "$gotxn" = "$wantx" ]; then ok
    else bad "the sex chromosome denominator is $gotx (--par none: $gotxn), chrX is $wantx"; fi

    # 12. The record says which convention produced the numbers, with or
    #     without the flag, and replays.
    m1=$(grep -c '"froh_denominator": "analyzed"' "$WORK/fd1.params.json")
    m2=$(grep -c '"froh_denominator": "assembly"' "$WORK/fd2.params.json")
    m3=$(grep -c '"chromosome_lengths": "build hg18"' "$WORK/fd2.params.json")
    if [ "$m1" -eq 1 ] && [ "$m2" -eq 1 ] && [ "$m3" -eq 1 ]; then ok
    else bad "the parameter record does not name the denominator and its source"; fi
    "$GARLIC" --load-params "$WORK/fd2.params.json" --out "$WORK/fd20" --force >/dev/null 2>&1
    if diff "$WORK/fd2.froh.tsv" "$WORK/fd20.froh.tsv" >/dev/null; then ok
    else bad "an assembly-denominator run did not replay from its parameter record"; fi
}

params_roundtrip() {
    echo "== params round trip =="
    $GARLIC --tped "$EX/chr21.tped.gz" --tfam "$EX/chr21.tfam.gz" --map "$EX/chr21.map.gz" \
            --weighted --build hg18 --winsize 60 --error 0.001 --froh \
            --out "$WORK/rt1" --quiet --force >/dev/null 2>&1
    $GARLIC --load-params "$WORK/rt1.params.json" --out "$WORK/rt2" --quiet --force >/dev/null 2>&1
    if [ "$(sum "$WORK/rt1.roh.bed")" = "$(sum "$WORK/rt2.roh.bed")" ] &&
       [ "$(sum "$WORK/rt1.froh.tsv")" = "$(sum "$WORK/rt2.froh.tsv")" ]; then ok
    else bad "--load-params did not reproduce the run it recorded"; fi

    # An explicit flag must win over the recorded value.
    $GARLIC --load-params "$WORK/rt1.params.json" --lod-cutoff 3.0 --out "$WORK/rt3" --quiet --force >/dev/null 2>&1
    if grep -q '"lod_cutoff": 3' "$WORK/rt3.params.json" 2>/dev/null; then ok
    else bad "a command line flag did not override the loaded params file"; fi
}

# ---------------------------------------------------------------------------
# 6. BED conformance
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# Counting classified genotypes inside and outside the calls (--features).
#
# The acceptance test is the comparison against count_features_in_roh.pl,
# which this replaces: same calls, same genotypes, same numbers.  It can only
# be run while that script is still in the tree, so it is guarded rather than
# assumed -- and the golden checksum below is what pins the output once the
# script is gone.
#
# The fixture relabels chr21 as chr22 because the tracked Perl begins its
# chromosome loop at a hardcoded `my $startchr = 22;` and cannot process
# anything else.  --no-centromere goes with it: the hg18 chr22 gap
# (11.3-14.2 Mb) overlaps chr21's coordinates, so without it garlic would
# correctly call those sites UNASSESSED while the Perl, which knows nothing
# about assembly gaps, called them NONE, and the comparison would fail for a
# reason that is not a disagreement about counting.
# ---------------------------------------------------------------------------
feature_counts() {
    echo "== feature counts =="
    FC=$WORK/fc
    mkdir -p "$FC"

    gz "$EX/chr21.tped.gz" | awk 'BEGIN{OFS="\t"}{$1="22"; print}' >"$FC/data.chr22.tped"
    gz "$EX/chr21.tfam.gz" >"$FC/data.chr22.tfam"
    # One class per site: the Perl's hash holds one class per (site, allele),
    # so a multi-class site is not something it can be compared on.
    awk 'NR%40==7 {print "22", $4, $5, (NR%3==0?"benign":(NR%3==1?"nonsyn":"damaging"))}' \
        "$FC/data.chr22.tped" >"$FC/feat.new"
    # The old four-column layout: chr:pos, ref, the classified allele, class.
    # 'N' for ref because the Perl files the class under the THIRD column and
    # only tests the second for equality; N never occurs in this data.
    awk '{print "chr22:"$2, "N", $3, $4}' "$FC/feat.new" >"$FC/feat.old"
    nfeat=$(wc -l <"$FC/feat.new" | tr -d ' ')

    $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
            --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
            --no-centromere --features "$FC/feat.new" \
            --out "$FC/g" --quiet --force >"$FC/g.stdout" 2>"$FC/g.stderr"
    if [ ! -f "$FC/g.counts.tsv" ]; then
        bad "--features wrote no counts file (see $FC/g.stderr)"; return
    fi
    ok

    # Not vacuous: something must actually have been counted inside a run.
    inroh=$(awk -F'\t' '/^##/ {next} NR_H==0 {NR_H=1; for(i=1;i<=NF;i++) h[$i]=i; next}
                        {n += $(h["benign_A_hom"]) + $(h["benign_B_hom"]) + $(h["benign_C_hom"])}
                        END {print n+0}' "$FC/g.counts.tsv")
    if [ "$inroh" -gt 0 ]; then ok
    else bad "no classified homozygote fell inside a run of homozygosity -- the case is vacuous"; fi

    # Every classified row lands in exactly one place, for every individual:
    # a bucket, or missing, or not-diploid.  This is the accounting the Perl
    # had no way to state, and it catches a genotype counted twice or lost.
    badrows=$(awk -F'\t' -v want="$nfeat" '
        /^##/ {next}
        NR_H==0 {NR_H=1; for(i=1;i<=NF;i++) h[$i]=i; next}
        {   t = $(h["benign_ALL_n"]) + $(h["damaging_ALL_n"]) + $(h["nonsyn_ALL_n"]) \
              + $(h["n_missing"]) + $(h["n_hemi"])
            if (t != want) n++ }
        END {print n+0}' "$FC/g.counts.tsv")
    if [ "$badrows" -eq 0 ]; then ok
    else bad "$badrows individual(s) where the classified rows do not add up to $nfeat"; fi

    # ALL is the sum of the buckets, so a reader can take "in ROH" as
    # ALL - NONE - UNASSESSED without re-deriving it.
    badsum=$(awk -F'\t' '
        /^##/ {next}
        NR_H==0 {NR_H=1; for(i=1;i<=NF;i++) h[$i]=i; next}
        {   s = $(h["benign_A_n"]) + $(h["benign_B_n"]) + $(h["benign_C_n"]) \
              + $(h["benign_NONE_n"]) + $(h["benign_UNASSESSED_n"])
            if (s != $(h["benign_ALL_n"])) n++ }
        END {print n+0}' "$FC/g.counts.tsv")
    if [ "$badsum" -eq 0 ]; then ok
    else bad "$badsum individual(s) where the bucket columns do not sum to ALL"; fi

    # THE ACCEPTANCE TEST.  Same .roh.bed, same genotypes, same homozygote
    # counts as the script being replaced.
    # count_features_in_roh.pl was removed once this comparison had passed, so
    # the skip below is the normal state of affairs and the golden checksum at
    # the end of this stage is what pins the numbers now.  Dropping a copy of
    # the script back into src/ re-enables the comparison.
    PL=$ROOT/src/count_features_in_roh.pl
    if [ ! -f "$PL" ] || ! command -v perl >/dev/null 2>&1; then
        echo "  SKIP  count_features_in_roh.pl comparison: the script it validated against is gone"
    else
        ( cd "$FC" && perl "$PL" feat.old g.roh.bed data.chr22.tped 22 perl.out ) \
            >"$FC/perl.stdout" 2>"$FC/perl.stderr"
        if [ ! -f "$FC/perl.out" ]; then
            bad "count_features_in_roh.pl produced no output (see $FC/perl.stderr)"
        else
            # The Perl writes <class><bucket> columns and a leading, unnamed
            # individual column; garlic writes <class>_<bucket>_hom among
            # others.  Compared by NAME on both sides rather than by position.
            awk 'NR==1 {for (i=1;i<=NF;i++) c[i]=$i; next}
                 {for (i=2;i<=NF;i++) print $1, c[i-1], $i}' "$FC/perl.out" \
                 | sort >"$FC/perl.flat"
            awk -F'\t' '
                /^##/ {next}
                NR_H==0 {NR_H=1; for (i=1;i<=NF;i++) h[i]=$i; next}
                {   for (i=1;i<=NF;i++) {
                        n = h[i]
                        if (n ~ /_hom$/) {
                            sub(/_hom$/, "", n)
                            # The Perl has no ALL and no UNASSESSED bucket.
                            if (n ~ /_ALL$/ || n ~ /_UNASSESSED$/) continue
                            sub(/_/, "", n)
                            print $1, n, $i } } }' "$FC/g.counts.tsv" \
                 | sort >"$FC/garlic.flat"
            if [ ! -s "$FC/garlic.flat" ]; then
                bad "no hom columns extracted from the counts file"
            elif diff -q "$FC/perl.flat" "$FC/garlic.flat" >/dev/null 2>&1; then
                ok
            else
                bad "garlic and count_features_in_roh.pl disagree: $(diff "$FC/perl.flat" "$FC/garlic.flat" | grep -c '^[<>]') differing cells"
                diff "$FC/perl.flat" "$FC/garlic.flat" | sed -n '1,6p' | sed 's/^/        /'
            fi
        fi
    fi

    # A site on a chromosome that was not analysed is UNASSESSED, not NONE.
    # Folding the two together is what inflates an outside-ROH count by
    # however much of the genome the user left out.
    gz "$EX/example.tped.gz" | awk '$1=="chr21" || $1=="21" {print $1, $4, $5, "onchr21"; exit}' \
        >"$FC/feat.two"
    gz "$EX/example.tped.gz" | awk '$1=="chr22" || $1=="22" {print $1, $4, $5, "onchr22"; exit}' \
        >>"$FC/feat.two"
    if [ "$(wc -l <"$FC/feat.two" | tr -d ' ')" -eq 2 ]; then
        $GARLIC --tped "$EX/example.tped.gz" --tfam "$EX/example.tfam" --build hg18 \
                --winsize 60 --error 0.001 --lod-cutoff 2.5 --size-bounds 500000 1000000 \
                --chr chr21 --features "$FC/feat.two" \
                --out "$FC/sub" --quiet --force >/dev/null 2>"$FC/sub.stderr"
        u=$(awk -F'\t' '/^##/ {next} NR_H==0 {NR_H=1; for(i=1;i<=NF;i++) h[$i]=i; next}
                        {n += $(h["onchr22_UNASSESSED_n"])} END {print n+0}' "$FC/sub.counts.tsv")
        z=$(awk -F'\t' '/^##/ {next} NR_H==0 {NR_H=1; for(i=1;i<=NF;i++) h[$i]=i; next}
                        {n += $(h["onchr22_NONE_n"])} END {print n+0}' "$FC/sub.counts.tsv")
        if [ "$u" -gt 0 ] && [ "$z" -eq 0 ]; then ok
        else bad "a site on an unanalysed chromosome: UNASSESSED=$u NONE=$z (want UNASSESSED>0, NONE=0)"; fi
    else
        echo "  SKIP  unanalysed-chromosome case: could not build a two-chromosome feature file"
    fi

    # Counting from a separate file must give what counting from the calling
    # input gives, when the two files are the same genotypes.
    $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
            --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
            --no-centromere --features "$FC/feat.new" \
            --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/data.chr22.tfam" \
            --out "$FC/sep" --quiet --force >/dev/null 2>"$FC/sep.stderr"
    if [ -f "$FC/sep.counts.tsv" ]; then
        grep -v '^## genotype_source' "$FC/g.counts.tsv"   >"$FC/g.nosrc"
        grep -v '^## genotype_source' "$FC/sep.counts.tsv" >"$FC/sep.nosrc"
        if cmp -s "$FC/g.nosrc" "$FC/sep.nosrc"; then ok
        else bad "--tped-counting over the calling file changed the counts"; fi
    else
        bad "--tped-counting wrote no counts file (see $FC/sep.stderr)"
    fi

    # The same genotypes as a VCF must give the same table.  The two readers
    # are independent code, and this is what keeps them from drifting.
    gz "$EX/chr21.tfam.gz" | awk '{printf "\t%s", $2} END{print ""}' >"$FC/vcf.samples"
    {
        printf '##fileformat=VCFv4.2\n'
        printf '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
        printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT'
        cat "$FC/vcf.samples"
        awk '{
            delete seen; n = 0
            for (i = 5; i <= NF; i++) if ($i != "0" && !($i in seen)) { seen[$i] = 1; a[++n] = $i }
            if (n == 0) next
            if (n == 1) { ref = a[1]; alt = (ref == "A" ? "C" : (ref == "C" ? "A" : (ref == "G" ? "T" : "G"))) }
            else if (a[1] < a[2]) { ref = a[1]; alt = a[2] }
            else                  { ref = a[2]; alt = a[1] }
            line = $1 "\t" $4 "\t" $2 "\t" ref "\t" alt "\t.\tPASS\t.\tGT"
            for (i = 5; i <= NF; i += 2) {
                if ($i == "0" || $(i+1) == "0") g = "./."
                else g = ($i == alt ? 1 : 0) "/" ($(i+1) == alt ? 1 : 0)
                line = line "\t" g
            }
            print line
        }' "$FC/data.chr22.tped"
    } >"$FC/data.chr22.vcf"

    $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
            --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
            --no-centromere --features "$FC/feat.new" \
            --vcf-counting "$FC/data.chr22.vcf" \
            --out "$FC/vc" --quiet --force >/dev/null 2>"$FC/vc.stderr"
    if [ -f "$FC/vc.counts.tsv" ]; then
        grep -v '^## genotype_source' "$FC/vc.counts.tsv" >"$FC/vc.nosrc"
        if cmp -s "$FC/g.nosrc" "$FC/vc.nosrc"; then ok
        else bad "counting the same genotypes from a VCF disagrees with the TPED path"; fi
    else
        bad "--vcf-counting wrote no counts file (see $FC/vc.stderr)"
    fi

    # An indel and a multiallelic site.  The reader that CALLS runs skips
    # both; the counter must not, because a classified variant is frequently
    # one or the other.  The genotypes cycle 0/0, 0/1, 1/1 over 45 samples,
    # so 15 homozygotes and 15 heterozygotes are the arithmetic.
    p1=$(awk 'NR==200 {print $4}' "$FC/data.chr22.tped")
    p2=$(awk 'NR==400 {print $4}' "$FC/data.chr22.tped")
    {
        printf '##fileformat=VCFv4.2\n'
        printf '#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT'
        cat "$FC/vcf.samples"
        printf '22\t%s\t.\tA\tATTG\t.\tPASS\t.\tGT' "$p1"
        awk 'BEGIN {for (i = 1; i <= 45; i++) printf "\t%s", (i%3==0 ? "0/0" : (i%3==1 ? "0/1" : "1/1")); print ""}'
        printf '22\t%s\t.\tC\tG,T\t.\tPASS\t.\tGT' "$p2"
        awk 'BEGIN {for (i = 1; i <= 45; i++) printf "\t%s", (i%3==0 ? "2/2" : (i%3==1 ? "0/2" : "0/0")); print ""}'
    } >"$FC/multi.vcf"
    printf '22 %s ATTG indel\n22 %s T trialt\n' "$p1" "$p2" >"$FC/feat.multi"
    $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
            --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
            --no-centromere --features "$FC/feat.multi" --vcf-counting "$FC/multi.vcf" \
            --out "$FC/mul" --quiet --force >/dev/null 2>"$FC/mul.stderr"
    if [ -f "$FC/mul.counts.tsv" ]; then
        got=$(awk -F'\t' '/^##/ {next}
                          NR_H==0 {NR_H=1; for(i=1;i<=NF;i++) h[$i]=i; next}
                          {   ih += $(h["indel_ALL_hom"]);  ie += $(h["indel_ALL_het"])
                              th += $(h["trialt_ALL_hom"]); te += $(h["trialt_ALL_het"])
                              nn += $(h["indel_ALL_n"]) + $(h["trialt_ALL_n"]) }
                          END {print ih":"ie":"th":"te":"nn}' "$FC/mul.counts.tsv")
        if [ "$got" = "15:15:15:15:90" ]; then ok
        else bad "indel and multiallelic counting: got $got, expected 15:15:15:15:90"; fi
    else
        bad "counting an indel and a multiallelic site wrote no file (see $FC/mul.stderr)"
    fi

    expect_exit 1 "--vcf-counting with --tped-counting" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
                --no-centromere --features "$FC/feat.new" \
                --vcf-counting "$FC/data.chr22.vcf" --tped-counting "$FC/data.chr22.tped" \
                --tfam-counting "$FC/data.chr22.tfam" --out "$FC/bad6" --quiet --force

    expect_exit 1 "--vcf-counting without --features" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
                --no-centromere --vcf-counting "$FC/data.chr22.vcf" \
                --out "$FC/bad7" --quiet --force

    # Sample IDs that match nothing must stop the run.  Left to itself this is
    # the failure that produces a complete, plausible, wrong table: every
    # homozygote reported as outside a run.
    sed 's/^\([^ 	]*\)\([ 	]\)\([^ 	]*\)/\1\2\3_OTHER/' "$FC/data.chr22.tfam" >"$FC/other.tfam"
    expect_exit 2 "counting samples that match no ROH call" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
                --no-centromere --features "$FC/feat.new" \
                --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/other.tfam" \
                --out "$FC/mismatch" --quiet --force

    # Feature-file refusals, where the wording is what the user sees.
    printf 'chr22:13823791 N A benign\n' >"$FC/oldfmt.txt"
    expect_exit 1 "a feature file still in the chr:pos format" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
                --features "$FC/oldfmt.txt" --no-centromere --out "$FC/bad1" --quiet --force
    if grep -q 'old count_features_in_roh.pl format' "$WORK/.expect_exit.err"; then ok
    else bad "the old-format refusal does not say how to convert the file"; fi

    printf '22 100 A benign\n22 100 A benign\n' >"$FC/dup.txt"
    expect_exit 1 "the same class twice at one site" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
                --features "$FC/dup.txt" --no-centromere --out "$FC/bad2" --quiet --force

    expect_exit 1 "--tped-counting without --tfam-counting" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
                --features "$FC/feat.new" --tped-counting "$FC/data.chr22.tped" \
                --no-centromere --out "$FC/bad3" --quiet --force

    expect_exit 1 "--tped-counting without --features" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --winsize 60 --error 0.001 --lod-cutoff 1.44 --size-bounds 300000 1000000 \
                --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/data.chr22.tfam" \
                --no-centromere --out "$FC/bad4" --quiet --force

    expect_exit 1 "--features with --freq-only" \
        $GARLIC --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --error 0.001 --freq-only --features "$FC/feat.new" \
                --out "$FC/bad5" --quiet --force

    # ---- counting against calls that already exist (--roh-file) ----
    #
    # The same calls, read back from the file garlic just wrote, must give the
    # same homozygote counts as counting inside the run that made them.
    $GARLIC --roh-file "$FC/g.roh.bed" --features "$FC/feat.new" \
            --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/data.chr22.tfam" \
            --out "$FC/sa" --quiet --force >/dev/null 2>"$FC/sa.stderr"
    if [ ! -f "$FC/sa.counts.tsv" ]; then
        bad "--roh-file wrote no counts file (see $FC/sa.stderr)"
    else
        homcells() {
            awk -F'\t' '/^##/ {next}
                        NR_H==0 {NR_H=1; for (i=1;i<=NF;i++) h[i]=$i; next}
                        {for (i=1;i<=NF;i++) if (h[i] ~ /_hom$/) print $1, h[i], $i}' "$1" | sort
        }
        homcells "$FC/g.counts.tsv"  >"$FC/g.hom"
        homcells "$FC/sa.counts.tsv" >"$FC/sa.hom"
        if cmp -s "$FC/g.hom" "$FC/sa.hom"; then ok
        else bad "counting against the written .roh.bed disagrees with counting inside the run"; fi

        # What the mode cannot know has to be said, not left blank.
        if grep -q '^## size_class_boundaries	unknown' "$FC/sa.counts.tsv" &&
           grep -q '^## unassessed	not determinable from a .roh.bed' "$FC/sa.counts.tsv"; then ok
        else bad "the --roh-file header does not record what a .roh.bed cannot say"; fi
    fi

    # A .roh.bed written before d5946c4 has a 1-based chromStart, and garlic
    # 1.1.6a was released with BOTH conventions -- so the version in the track
    # line cannot distinguish them and the file itself has to.
    awk 'BEGIN {OFS="\t"} /^track/ {print; next} {$2 = $2 + 1; print}' \
        "$FC/g.roh.bed" >"$FC/legacy.roh.bed"
    $GARLIC --roh-file "$FC/legacy.roh.bed" --features "$FC/feat.new" \
            --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/data.chr22.tfam" \
            --out "$FC/lg" --quiet --force >/dev/null 2>"$FC/lg.stderr"
    if [ ! -f "$FC/lg.counts.tsv" ]; then
        bad "a pre-2.0.0 .roh.bed was not read (see $FC/lg.stderr)"
    else
        homcells "$FC/lg.counts.tsv" >"$FC/lg.hom"
        if cmp -s "$FC/sa.hom" "$FC/lg.hom"; then ok
        else bad "a pre-2.0.0 .roh.bed gives different counts -- the coordinate shift is wrong"; fi
        if grep -q 'pre-2.0.0 coordinate convention' "$FC/lg.log"; then ok
        else bad "reading a pre-2.0.0 .roh.bed did not say so in the log"; fi
    fi

    # Half one convention and half the other is two files concatenated, and
    # there is no reading of it that is right.
    { head -20 "$FC/g.roh.bed"; sed -n '21,40p' "$FC/legacy.roh.bed"; } >"$FC/mixed.roh.bed"
    expect_exit 2 "a .roh.bed mixing both coordinate conventions" \
        $GARLIC --roh-file "$FC/mixed.roh.bed" --features "$FC/feat.new" \
                --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/data.chr22.tfam" \
                --out "$FC/mx" --quiet --force

    expect_exit 1 "--roh-file without --features" \
        $GARLIC --roh-file "$FC/g.roh.bed" \
                --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/data.chr22.tfam" \
                --out "$FC/bad8" --quiet --force

    expect_exit 1 "--roh-file without genotypes to count" \
        $GARLIC --roh-file "$FC/g.roh.bed" --features "$FC/feat.new" \
                --out "$FC/bad9" --quiet --force

    expect_exit 1 "--roh-file together with a calling input" \
        $GARLIC --roh-file "$FC/g.roh.bed" --features "$FC/feat.new" \
                --tped "$FC/data.chr22.tped" --tfam "$FC/data.chr22.tfam" \
                --tped-counting "$FC/data.chr22.tped" --tfam-counting "$FC/data.chr22.tfam" \
                --out "$FC/bad10" --quiet --force

    # Golden: what pins the output once the Perl comparison above is gone.
    # The two header lines naming input paths carry $WORK, which contains the
    # test run's pid, so they are stripped before checksumming.
    grep -v -e '^## feature_file' -e '^## genotype_source' "$FC/g.counts.tsv" >"$FC/g.golden"
    got=$(sum "$FC/g.golden")
    g=$GOLDEN/fc_chr22.counts.tsv.md5
    if [ "$BLESS" = yes ]; then
        echo "$got" >"$g"; ok
    elif [ ! -f "$g" ]; then
        bad "fc_chr22.counts.tsv: no golden checksum (run with --bless)"
    elif [ "$got" = "$(cat "$g")" ]; then ok
    else bad "fc_chr22.counts.tsv: $got != $(cat "$g") (output kept at $FC/g.counts.tsv)"; fi
}

bed_format() {
    echo "== bed format =="
    f=$WORK/c21_unweighted.roh.bed
    [ -f "$f" ] || { bad "no bed file to check (golden stage did not run)"; return; }
    bad_rows=$(grep -v '^track' "$f" | awk '$3-$2 != $5 || $2 < 0 {n++} END {print n+0}')
    if [ "$bad_rows" -eq 0 ]; then ok
    else bad "$bad_rows rows where chromEnd-chromStart != length, or chromStart < 0"; fi
}

